// Regenerates the documentation site's reference data from the compiler, so
// the site can never describe a sentence or an error code that does not exist.
// Run after `npm run build`: node scripts/generate-site-data.mjs
// test/f7-site.test.mjs fails when the files are out of date.
import { writeFileSync } from "node:fs";

const { STATEMENT_TEMPLATES } = await import("../dist/core/parser/registry.js");
const { CODE_EXPLANATIONS } = await import("../dist/core/diagnostics/explanations.js");
const { builtInFonts, fontCatalog } = await import("../dist/fonts/catalog.js");

const sentences = STATEMENT_TEMPLATES
  .filter((template) => (template.examples ?? []).length > 0)
  .map((template) => ({
    name: template.description,
    version: template.since ?? "0.1",
    examples: template.examples.slice(0, 3).join("   ·   "),
  }))
  .sort((a, b) => (a.name.toLowerCase() < b.name.toLowerCase() ? -1 : a.name.toLowerCase() > b.name.toLowerCase() ? 1 : 0));
const codes = CODE_EXPLANATIONS.map((entry) => ({ code: entry.code, area: entry.area, meaning: entry.meaning }));

writeFileSync("site/data/sentences.json", `${JSON.stringify(sentences, null, 2)}\n`);
writeFileSync("site/data/codes.json", `${JSON.stringify(codes, null, 2)}\n`);

// D-51: the font gallery shows every built-in family in its own font.
const STYLE_NAMES = { "sans-serif": "Sans serif", serif: "Serif", monospace: "Monospace", display: "Display", handwriting: "Handwriting", other: "Other" };
const builtIn = [...builtInFonts().values()].sort((a, b) => (a.family < b.family ? -1 : a.family > b.family ? 1 : 0));
const groups = Object.keys(STYLE_NAMES).map((category) => [category, builtIn.filter((font) => font.category === category)]).filter(([, fonts]) => fonts.length > 0);
const quote = (text) => JSON.stringify(text);
const gallery = [
  "kadam 0.4",
  "// Generated by scripts/generate-site-data.mjs from the built-in fonts (D-51). Do not edit.",
  "",
  'The page is called "Fonts".',
  "The page background is paper.",
  "The page text is ink.",
  "The page is dark when the system is dark.",
  "",
  "A SiteHeader.",
  "",
  "Fonts section:",
  "    It is full width. It is at most 960px wide. It is centered.",
  "    It has 40px padding on the top and bottom and 24px padding on the left and right.",
  "    It has 14px gap between children.",
  "",
  '    A big heading says "Fonts". The text is between 2rem and 2.5rem.',
  `    Muted text, 18px, says ${quote(`${builtIn.length} free fonts are built in: name one and it works, with no files to download. The other ${fontCatalog().length - builtIn.length} free fonts are one command away, and your own font files go in the fonts folder.`)}`,
  `    A code block says ${quote('The page font is Lora.\nThe heading font is Playfair Display.\nText says "Note". The font is Caveat.')}`,
  `    A code block says ${quote('kadam fonts list --category serif\nkadam fonts add "Noto Sans JP"')}`,
  ...groups.flatMap(([category, fonts]) => [
    "",
    `    A heading says ${quote(`${STYLE_NAMES[category]} (${fonts.length})`)}.`,
    "    In 3 columns with 16px gap:",
    ...fonts.flatMap((font) => [
      "        A card:",
      "            It has 6px gap between children.",
      `            Muted small text says ${quote(font.family)}.`,
      `            Text, 22px, says "The quick brown fox jumps over the lazy dog". The font is ${quote(font.family)}.`,
    ]),
  ]),
  "",
].join("\n");
writeFileSync("site/pages/fonts.kdm", gallery);
console.log(`wrote ${sentences.length} sentences, ${codes.length} codes and ${builtIn.length} fonts`);
