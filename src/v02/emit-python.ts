import type {
  CoreType,
  IrBlock,
  IrExpression,
  IrFunction,
  IrModule,
  IrStatement,
} from "./ir.js";
import {
  pythonNumberLiteral,
  pythonString,
  type ExternalBinding,
  type OutputFile,
} from "./target.js";

const RUNTIME: readonly string[] = [
  "class KadamRuntimeError(Exception):",
  "    pass",
  "",
  "",
  "def kadam_fail(category: str) -> None:",
  "    raise KadamRuntimeError(category)",
  "",
  "",
  "def kadam_format_number(value: float) -> str:",
  "    value = float(value)",
  "    if not math.isfinite(value):",
  '        kadam_fail("non-finite number")',
  "    if value == 0.0:",
  '        return "0"',
  "    magnitude = abs(value)",
  "    if 1e-6 <= magnitude < 1e21:",
  "        if value.is_integer():",
  "            return str(int(value))",
  '        return format(Decimal(repr(value)), "f")',
  "    text = repr(value)",
  '    mantissa, exponent = text.split("e")',
  '    if mantissa.endswith(".0"):',
  "        mantissa = mantissa[:-2]",
  '    return mantissa + "e" + str(int(exponent))',
  "",
  "",
  "def kadam_output(value: object) -> None:",
  "    if isinstance(value, str):",
  "        text = value",
  "    elif isinstance(value, bool):",
  '        text = "true" if value else "false"',
  "    elif isinstance(value, (int, float)):",
  "        text = kadam_format_number(float(value))",
  "    else:",
  '        kadam_fail("output requires text, number, or boolean")',
  '    sys.stdout.buffer.write((text + "\\n").encode("utf-8"))',
  "",
  "",
  "def kadam_read_text(path: str) -> str:",
  "    try:",
  '        with open(path, "rb") as handle:',
  "            data = handle.read()",
  '        return data.decode("utf-8")',
  "    except (OSError, UnicodeDecodeError):",
  '        kadam_fail("file read failed")',
  "",
  "",
  "def kadam_write_text(path: str, contents: str) -> None:",
  "    try:",
  "        with open(path, \"wb\") as handle:",
  '            handle.write(contents.encode("utf-8"))',
  "    except (OSError, UnicodeEncodeError):",
  '        kadam_fail("file write failed")',
  "",
  "",
  "def kadam_finite(value: float) -> float:",
  "    if not math.isfinite(value):",
  '        kadam_fail("non-finite number")',
  "    return value",
  "",
  "",
  "def kadam_add(left: float, right: float) -> float:",
  "    return kadam_finite(left + right)",
  "",
  "",
  "def kadam_sub(left: float, right: float) -> float:",
  "    return kadam_finite(left - right)",
  "",
  "",
  "def kadam_mul(left: float, right: float) -> float:",
  "    return kadam_finite(left * right)",
  "",
  "",
  "def kadam_div(left: float, right: float) -> float:",
  "    if right == 0.0:",
  '        kadam_fail("division by zero")',
  "    return kadam_finite(left / right)",
  "",
  "",
  "def kadam_neg(value: float) -> float:",
  "    return kadam_finite(-value)",
  "",
  "",
  "def kadam_index(values: object, index: object) -> object:",
  "    if isinstance(index, bool) or not isinstance(index, (int, float)):",
  '        kadam_fail("list index out of bounds")',
  "    if not math.isfinite(index) or not float(index).is_integer():",
  '        kadam_fail("list index out of bounds")',
  "    resolved = int(index)",
  "    if resolved < 0 or resolved >= len(values):",
  '        kadam_fail("list index out of bounds")',
  "    return values[resolved]",
];

export function emitPython(
  program: IrModule,
  bindings: readonly ExternalBinding[],
): OutputFile {
  const lines: string[] = [
    `# Generated by Kadam target "python" from ${JSON.stringify(
      program.sourceFile,
    )}. Do not edit.`,
    "from __future__ import annotations",
    "",
    "import math",
    "import sys",
    "from decimal import Decimal",
  ];

  if (program.records.length > 0) {
    lines.push("from dataclasses import dataclass");
  }
  for (const binding of bindings) {
    const [moduleName, nativeName] = splitProvider(binding.provider.symbol);
    lines.push(`from ${moduleName} import ${nativeName} as ${binding.alias}`);
  }
  lines.push("");

  lines.push(...RUNTIME, "");

  for (const record of program.records) {
    lines.push("@dataclass(frozen=True)", `class ${recordName(record.name)}:`);
    if (record.fields.length === 0) {
      lines.push("    pass", "");
      continue;
    }
    for (const field of record.fields) {
      lines.push(`    ${fieldName(field.name)}: ${typeText(field.type)}`);
    }
    lines.push("");
  }

  for (const binding of bindings) {
    lines.push(...emitExternalWrapper(binding), "");
  }

  for (const fn of program.functions) {
    lines.push(...emitFunction(fn), "");
  }

  if (program.main !== null) {
    lines.push(
      'if __name__ == "__main__":',
      "    try:",
      `        kadam_status = ${valueName(program.main.name)}()`,
      "        if isinstance(kadam_status, bool) or not isinstance(kadam_status, (int, float)):",
      '            kadam_fail("invalid program status")',
      "        if (",
      "            not math.isfinite(kadam_status)",
      "            or not float(kadam_status).is_integer()",
      "            or kadam_status < 0",
      "            or kadam_status > 255",
      "        ):",
      '            kadam_fail("invalid program status")',
      "        sys.exit(int(kadam_status))",
      "    except KadamRuntimeError as error:",
      '        sys.stderr.write("kadam runtime failure: " + str(error) + "\\n")',
      "        sys.exit(1)",
      "    except Exception:",
      '        sys.stderr.write("kadam runtime failure: runtime failure\\n")',
      "        sys.exit(1)",
    );
  }

  return {
    path: "main.py",
    contents: `${lines.join("\n").replace(/\n{3,}/g, "\n\n")}\n`,
  };
}

function emitExternalWrapper(binding: ExternalBinding): string[] {
  const fn = binding.external;
  const parameters = fn.parameters
    .map((parameter) => `${valueName(parameter.name)}: ${typeText(parameter.type)}`)
    .join(", ");
  const args = fn.parameters.map((parameter) => valueName(parameter.name)).join(", ");
  const lines = [
    `def ${valueName(fn.name)}(${parameters}) -> ${typeText(fn.returnType)}:`,
  ];
  if (fn.returnType.kind === "nothing") {
    lines.push(`    ${binding.alias}(${args})`);
  } else {
    lines.push(`    return ${binding.alias}(${args})`);
  }
  return lines;
}

function emitFunction(fn: IrFunction): string[] {
  const parameters = fn.parameters
    .map((parameter) => `${valueName(parameter.name)}: ${typeText(parameter.type)}`)
    .join(", ");
  const lines = [
    `def ${valueName(fn.name)}(${parameters}) -> ${typeText(fn.returnType)}:`,
  ];
  const body = emitBlock(fn.body, 1);
  lines.push(...(body.length === 0 ? ["    pass"] : body));
  return lines;
}

function emitBlock(block: IrBlock, level: number): string[] {
  const lines: string[] = [];
  for (const statement of block.statements) {
    lines.push(...emitStatement(statement, level));
  }
  return lines;
}

function emitStatement(statement: IrStatement, level: number): string[] {
  const indent = "    ".repeat(level);
  switch (statement.kind) {
    case "local":
      return [`${indent}${valueName(statement.name)} = ${expression(statement.initializer)}`];
    case "set":
      return [`${indent}${valueName(statement.name)} = ${expression(statement.value)}`];
    case "if": {
      const lines = [
        `${indent}if ${expression(statement.condition)}:`,
        ...indentedBlock(statement.thenBlock, level + 1),
      ];
      if (statement.otherwiseBlock !== null) {
        lines.push(`${indent}else:`);
        lines.push(...indentedBlock(statement.otherwiseBlock, level + 1));
      }
      return lines;
    }
    case "while":
      return [
        `${indent}while ${expression(statement.condition)}:`,
        ...indentedBlock(statement.body, level + 1),
      ];
    case "return":
      return [
        statement.value === null
          ? `${indent}return`
          : `${indent}return ${expression(statement.value)}`,
      ];
    case "output":
      return [`${indent}kadam_output(${expression(statement.value)})`];
    case "expression":
      return [`${indent}${expression(statement.expression)}`];
  }
}

function indentedBlock(block: IrBlock, level: number): string[] {
  const lines = emitBlock(block, level);
  return lines.length === 0 ? [`${"    ".repeat(level)}pass`] : lines;
}

function expression(node: IrExpression): string {
  switch (node.kind) {
    case "text":
      return pythonString(node.value);
    case "number":
      return pythonNumberLiteral(node.value);
    case "boolean":
      return node.value ? "True" : "False";
    case "name":
      return valueName(node.name);
    case "list":
      return node.elements.length === 0
        ? "()"
        : `(${node.elements.map(expression).join(", ")}${
            node.elements.length === 1 ? "," : ""
          })`;
    case "record":
      return `${recordName(node.typeName)}(${node.fields
        .map((field) => `${fieldName(field.name)}=${expression(field.value)}`)
        .join(", ")})`;
    case "unary":
      return node.operator === "not"
        ? `(not ${expression(node.operand)})`
        : `kadam_neg(${expression(node.operand)})`;
    case "binary":
      return emitBinary(node.operator, node.left, node.right, node.type);
    case "field":
      return `(${expression(node.target)}).${fieldName(node.field)}`;
    case "index":
      return `kadam_index(${expression(node.target)}, ${expression(node.index)})`;
    case "call":
      return emitCall(node);
  }
}

function emitBinary(
  operator: string,
  left: IrExpression,
  right: IrExpression,
  type: CoreType,
): string {
  const lhs = expression(left);
  const rhs = expression(right);
  switch (operator) {
    case "and":
      return `(${lhs} and ${rhs})`;
    case "or":
      return `(${lhs} or ${rhs})`;
    case "==":
    case "!=":
    case "<":
    case "<=":
    case ">":
    case ">=":
      return `(${lhs} ${operator} ${rhs})`;
    case "+":
      return type.kind === "text" ? `(${lhs} + ${rhs})` : `kadam_add(${lhs}, ${rhs})`;
    case "-":
      return `kadam_sub(${lhs}, ${rhs})`;
    case "*":
      return `kadam_mul(${lhs}, ${rhs})`;
    case "/":
      return `kadam_div(${lhs}, ${rhs})`;
    default:
      throw new Error(`unsupported binary operator ${operator}`);
  }
}

function emitCall(node: Extract<IrExpression, { kind: "call" }>): string {
  const args = node.arguments.map(expression).join(", ");
  if (node.callKind === "intrinsic") {
    if (node.callee === "length") return `len(${args})`;
    if (node.callee === "readText") return `kadam_read_text(${args})`;
    if (node.callee === "writeText") return `kadam_write_text(${args})`;
    throw new Error(`unsupported intrinsic ${node.callee}`);
  }
  return `${valueName(node.callee)}(${args})`;
}

function typeText(type: CoreType): string {
  switch (type.kind) {
    case "text":
      return "str";
    case "number":
      return "float";
    case "boolean":
      return "bool";
    case "nothing":
      return "None";
    case "list":
      return `tuple[${typeText(type.element)}, ...]`;
    case "record":
      return recordName(type.name);
  }
}

function valueName(name: string): string {
  return `k_${name}`;
}

function fieldName(name: string): string {
  return `k_${name}`;
}

function recordName(name: string): string {
  return `KadamRecord_${name}`;
}

function splitProvider(symbol: string): readonly [string, string] {
  const hash = symbol.indexOf("#");
  return [symbol.slice(0, hash), symbol.slice(hash + 1)];
}
