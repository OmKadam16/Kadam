import type {
  CoreType,
  IrBlock,
  IrExpression,
  IrFunction,
  IrModule,
  IrStatement,
} from "./ir.js";
import {
  formatCoreNumber,
  typescriptString,
  type ExternalBinding,
  type OutputFile,
} from "./target.js";

const RUNTIME: readonly string[] = [
  "class KadamRuntimeError extends Error {",
  "  constructor(category: string) {",
  "    super(category);",
  '    this.name = "KadamRuntimeError";',
  "  }",
  "}",
  "",
  "function kadam_fail(category: string): never {",
  "  throw new KadamRuntimeError(category);",
  "}",
  "",
  "const kadam_decoder = new TextDecoder(\"utf-8\", { fatal: true });",
  "",
  "function kadam_format_number(value: number): string {",
  "  if (!Number.isFinite(value)) return kadam_fail(\"non-finite number\");",
  "  if (Object.is(value, -0) || value === 0) return \"0\";",
  "  let text = value.toString();",
  "  if (text.includes(\"e\")) {",
  "    text = text.replace(\"e+\", \"e\");",
  "    text = text.replace(/e(-?)0+(\\d+)/, \"e$1$2\");",
  "  }",
  "  return text;",
  "}",
  "",
  "function kadam_output(value: string | number | boolean): void {",
  "  let text: string;",
  "  if (typeof value === \"string\") text = value;",
  "  else if (typeof value === \"boolean\") text = value ? \"true\" : \"false\";",
  "  else text = kadam_format_number(value);",
  "  process.stdout.write(text + \"\\n\", \"utf8\");",
  "}",
  "",
  "function kadam_read_text(path: string): string {",
  "  try {",
  "    return kadam_decoder.decode(readFileSync(path));",
  "  } catch {",
  "    return kadam_fail(\"file read failed\");",
  "  }",
  "}",
  "",
  "function kadam_write_text(path: string, contents: string): void {",
  "  try {",
  "    writeFileSync(path, contents, \"utf8\");",
  "  } catch {",
  "    kadam_fail(\"file write failed\");",
  "  }",
  "}",
  "",
  "function kadam_finite(value: number): number {",
  "  if (!Number.isFinite(value)) return kadam_fail(\"non-finite number\");",
  "  return value;",
  "}",
  "",
  "function kadam_add(left: number, right: number): number {",
  "  return kadam_finite(left + right);",
  "}",
  "",
  "function kadam_sub(left: number, right: number): number {",
  "  return kadam_finite(left - right);",
  "}",
  "",
  "function kadam_mul(left: number, right: number): number {",
  "  return kadam_finite(left * right);",
  "}",
  "",
  "function kadam_div(left: number, right: number): number {",
  "  if (right === 0) return kadam_fail(\"division by zero\");",
  "  return kadam_finite(left / right);",
  "}",
  "",
  "function kadam_neg(value: number): number {",
  "  return kadam_finite(-value);",
  "}",
  "",
  "function kadam_index<T>(values: readonly T[], index: number): T {",
  "  if (!Number.isInteger(index) || index < 0 || index >= values.length) {",
  "    return kadam_fail(\"list index out of bounds\");",
  "  }",
  "  return values[index]!;",
  "}",
  "",
  "function kadam_list<T>(values: readonly T[]): readonly T[] {",
  "  return Object.freeze(values.slice());",
  "}",
];

export function emitTypeScript(
  program: IrModule,
  bindings: readonly ExternalBinding[],
): OutputFile {
  const lines: string[] = [
    `// Generated by Kadam target "typescript" from ${typescriptString(
      program.sourceFile,
    )}. Do not edit.`,
    'import { readFileSync, writeFileSync } from "node:fs";',
  ];

  for (const binding of bindings) {
    const [moduleName, nativeName] = splitProvider(binding.provider.symbol);
    lines.push(
      `import { ${nativeName} as ${binding.alias} } from ${typescriptString(
        moduleName,
      )};`,
    );
  }
  lines.push("");

  for (const record of program.records) {
    lines.push(`type ${recordName(record.name)} = {`);
    for (const field of record.fields) {
      lines.push(`  readonly ${fieldName(field.name)}: ${typeText(field.type)};`);
    }
    lines.push("};", "");
  }

  lines.push(...RUNTIME, "");

  for (const binding of bindings) {
    lines.push(...emitExternalWrapper(binding), "");
  }

  for (const fn of program.functions) {
    lines.push(...emitFunction(fn), "");
  }

  if (program.main !== null) {
    lines.push(
      "try {",
      `  const kadam_status = ${valueName(program.main.name)}();`,
      "  if (!Number.isInteger(kadam_status) || kadam_status < 0 || kadam_status > 255) {",
      '    kadam_fail("invalid program status");',
      "  }",
      "  process.exitCode = kadam_status;",
      "} catch (error) {",
      '  const message = error instanceof KadamRuntimeError ? error.message : "runtime failure";',
      '  process.stderr.write("kadam runtime failure: " + message + "\\n", "utf8");',
      "  process.exitCode = 1;",
      "}",
    );
  }

  return {
    path: "main.ts",
    contents: `${lines.join("\n").replace(/\n{3,}/g, "\n\n")}\n`,
  };
}

function emitExternalWrapper(binding: ExternalBinding): string[] {
  const fn = binding.external;
  const parameters = fn.parameters
    .map((parameter) => `${valueName(parameter.name)}: ${typeText(parameter.type)}`)
    .join(", ");
  const args = fn.parameters.map((parameter) => valueName(parameter.name)).join(", ");
  const lines = [
    `function ${valueName(fn.name)}(${parameters}): ${typeText(fn.returnType)} {`,
  ];
  if (fn.returnType.kind === "nothing") {
    lines.push(`  ${binding.alias}(${args});`);
  } else {
    lines.push(`  return ${binding.alias}(${args});`);
  }
  lines.push("}");
  return lines;
}

function emitFunction(fn: IrFunction): string[] {
  const parameters = fn.parameters
    .map((parameter) => `${valueName(parameter.name)}: ${typeText(parameter.type)}`)
    .join(", ");
  const lines = [
    `function ${valueName(fn.name)}(${parameters}): ${typeText(fn.returnType)} {`,
    ...emitBlock(fn.body, 1),
    "}",
  ];
  return lines;
}

function emitBlock(block: IrBlock, level: number): string[] {
  const lines: string[] = [];
  for (const statement of block.statements) {
    lines.push(...emitStatement(statement, level));
  }
  return lines;
}

function emitStatement(statement: IrStatement, level: number): string[] {
  const indent = "  ".repeat(level);
  switch (statement.kind) {
    case "local":
      return [
        `${indent}${statement.mutable ? "let" : "const"} ${valueName(
          statement.name,
        )} = ${expression(statement.initializer)};`,
      ];
    case "set":
      return [
        `${indent}${valueName(statement.name)} = ${expression(statement.value)};`,
      ];
    case "if": {
      const lines = [
        `${indent}if (${expression(statement.condition)}) {`,
        ...emitBlock(statement.thenBlock, level + 1),
        `${indent}}`,
      ];
      if (statement.otherwiseBlock !== null) {
        lines[lines.length - 1] = `${indent}} else {`;
        lines.push(
          ...emitBlock(statement.otherwiseBlock, level + 1),
          `${indent}}`,
        );
      }
      return lines;
    }
    case "while":
      return [
        `${indent}while (${expression(statement.condition)}) {`,
        ...emitBlock(statement.body, level + 1),
        `${indent}}`,
      ];
    case "return":
      return [
        statement.value === null
          ? `${indent}return;`
          : `${indent}return ${expression(statement.value)};`,
      ];
    case "output":
      return [`${indent}kadam_output(${expression(statement.value)});`];
    case "expression":
      return [`${indent}${expression(statement.expression)};`];
  }
}

function expression(node: IrExpression): string {
  switch (node.kind) {
    case "text":
      return typescriptString(node.value);
    case "number":
      return formatCoreNumber(node.value);
    case "boolean":
      return node.value ? "true" : "false";
    case "name":
      return valueName(node.name);
    case "list":
      return `kadam_list([${node.elements.map(expression).join(", ")}])`;
    case "record":
      return `Object.freeze({ ${node.fields
        .map((field) => `${fieldName(field.name)}: ${expression(field.value)}`)
        .join(", ")} })`;
    case "unary":
      return node.operator === "not"
        ? `(!${expression(node.operand)})`
        : `kadam_neg(${expression(node.operand)})`;
    case "binary":
      return emitBinary(node.operator, node.left, node.right, node.type);
    case "field":
      return `(${expression(node.target)}).${fieldName(node.field)}`;
    case "index":
      return `kadam_index(${expression(node.target)}, ${expression(node.index)})`;
    case "call":
      return emitCall(node);
  }
}

function emitBinary(
  operator: string,
  left: IrExpression,
  right: IrExpression,
  type: CoreType,
): string {
  const lhs = expression(left);
  const rhs = expression(right);
  switch (operator) {
    case "and":
      return `(${lhs} && ${rhs})`;
    case "or":
      return `(${lhs} || ${rhs})`;
    case "==":
      return `(${lhs} === ${rhs})`;
    case "!=":
      return `(${lhs} !== ${rhs})`;
    case "<":
    case "<=":
    case ">":
    case ">=":
      return `(${lhs} ${operator} ${rhs})`;
    case "+":
      return type.kind === "text" ? `(${lhs} + ${rhs})` : `kadam_add(${lhs}, ${rhs})`;
    case "-":
      return `kadam_sub(${lhs}, ${rhs})`;
    case "*":
      return `kadam_mul(${lhs}, ${rhs})`;
    case "/":
      return `kadam_div(${lhs}, ${rhs})`;
    default:
      throw new Error(`unsupported binary operator ${operator}`);
  }
}

function emitCall(node: Extract<IrExpression, { kind: "call" }>): string {
  const args = node.arguments.map(expression).join(", ");
  if (node.callKind === "intrinsic") {
    if (node.callee === "length") return `(${args}).length`;
    if (node.callee === "readText") return `kadam_read_text(${args})`;
    if (node.callee === "writeText") return `kadam_write_text(${args})`;
    throw new Error(`unsupported intrinsic ${node.callee}`);
  }
  return `${valueName(node.callee)}(${args})`;
}

function typeText(type: CoreType): string {
  switch (type.kind) {
    case "text":
      return "string";
    case "number":
      return "number";
    case "boolean":
      return "boolean";
    case "nothing":
      return "void";
    case "list":
      return `readonly (${typeText(type.element)})[]`;
    case "record":
      return recordName(type.name);
  }
}

function valueName(name: string): string {
  return `k_${name}`;
}

function fieldName(name: string): string {
  return `k_${name}`;
}

function recordName(name: string): string {
  return `KadamRecord_${name}`;
}

function splitProvider(symbol: string): readonly [string, string] {
  const hash = symbol.indexOf("#");
  return [symbol.slice(0, hash), symbol.slice(hash + 1)];
}
