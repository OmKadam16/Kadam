export function emitPageCss(page: PageIR): string {
  const blocks: string[] = [
    "/* Generated by Kadam 0.1. Do not edit. */",
    ...(page.fonts ?? []).map((font) =>
      cssRule("@font-face", [
        ["font-family", `"${font.family}"`],
        ["src", `url("${font.url}") format("${font.format}")`],
        ["font-weight", font.weight],
        ["font-style", font.style],
        ["font-display", "swap"],
        ...(font.unicodeRange === undefined ? [] : [["unicode-range", font.unicodeRange] as Declaration]),
      ]),
    ),
    cssRule("body", [
      ["background-color", formatColor(page.pageStyle.background)],
    ]),
    // kadam 0.3: a page-level header or footer is emitted outside <main>, so
    // it shares the page text color and font through .kdm-page-landmark.
    cssRule(hasPageLandmarks(page) ? ".kdm-page,\n.kdm-page-landmark" : ".kdm-page", [
      ["color", formatColor(page.pageStyle.text)],
      ["font-family", page.pageStyle.fontStack ?? FONT_STACKS[page.pageStyle.font]],
    ]),
    ...(page.pageStyle.headingFontStack === undefined ? [] : [
      cssRule(":where(.kdm-page, .kdm-page-landmark) :is(.kdm-kind-main-heading, .kdm-kind-section-heading, .kdm-kind-minor-heading)", [["font-family", page.pageStyle.headingFontStack]]),
    ]),
    ...themeBlocks(page),
  ];

  const elements = uniqueByClassName(flatten(page.elements));
  // kadam 0.3: one rule per color that inline words use.
  const wordColors = new Map<string, string>();
  for (const element of flatten(page.elements)) {
    for (const segment of element.text?.segments ?? []) {
      if (segment.type === "color" && !wordColors.has(segment.className)) wordColors.set(segment.className, segment.color);
    }
  }
  for (const [className, value] of [...wordColors].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))) {
    blocks.push(cssRule(`.${className}`, [["color", value]]));
  }
  // D-50: highlights that sweep under words, one rule per color.
  const highlights = new Map<string, string>();
  for (const element of flatten(page.elements)) {
    for (const segment of element.text?.segments ?? []) {
      if (segment.type === "highlight" && !highlights.has(segment.className)) highlights.set(segment.className, segment.color);
    }
  }
  if (highlights.size > 0) {
    blocks.push(cssRule(".kdm-highlight", [["padding", "0 0.1em"], ["color", "inherit"], ["background-color", "transparent"], ["background-repeat", "no-repeat"],
      ["background-position", "0 88%"], ["background-size", "100% 42%"], ["animation", "kdm-highlight-sweep 900ms ease-out 300ms both"]]));
    blocks.push(keyframes("kdm-highlight-sweep", [["from", [["background-size", "0% 42%"]]]]));
    for (const [className, value] of [...highlights].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))) {
      blocks.push(cssRule(`.${className}`, [["background-image", `linear-gradient(${value}, ${value})`]]));
    }
  }
  // D-50: how the page comes in, and the page-to-page transition.
  if (page.meta?.enter !== undefined) {
    blocks.push(cssRule("body", [["animation", `kdm-page-${page.meta.enter} 500ms ease-out both`]]));
    blocks.push(keyframes(`kdm-page-${page.meta.enter}`, page.meta.enter === "fade" ? [["from", [["opacity", "0"]]]] : [["from", [["opacity", "0"], ["translate", "0 16px"]]]]));
  }
  if (page.meta?.transition === "cross-fade") blocks.push("@view-transition {\n  navigation: auto;\n}");
  for (const element of elements) {
    blocks.push(...baseRules(element));
    for (const rule of element.rules ?? []) {
      if (rule.at === null) blocks.push(cssRule(rule.selector, toDeclarations(rule.declarations)));
    }
  }

  for (const breakpoint of ["phones", "tablets", "desktops"] as const) {
    const rules: string[] = [];
    for (const element of elements) {
      const responsive = element.responsive.find(
        (entry) => entry.breakpoint === breakpoint,
      );
      if (responsive === undefined) continue;
      rules.push(...responsiveRules(element, responsive.authored, responsive.style));
    }
    if (rules.length > 0) {
      blocks.push(mediaBlock(breakpointQuery(breakpoint), rules));
    }
  }

  // kadam 0.3 custom breakpoints and container queries, most specific last.
  const scoped = new Map<string, { order: number; rules: string[] }>();
  for (const element of elements) {
    for (const scope of element.scopes ?? []) {
      const entry = scoped.get(scope.query) ?? { order: scope.order, rules: [] };
      const rules = responsiveRules(element, scope.authored, scope.style);
      // kadam 0.3: a state style is the element's own selector plus the attribute the runtime sets.
      entry.rules.push(...(scope.query.startsWith("[") ? rules.map((rule) => rule.split(`.${element.className}`).join(`.${element.className}${scope.query}`)) : rules));
      scoped.set(scope.query, entry);
    }
  }
  const scopedBlocks = [...scoped.entries()]
    .filter(([, entry]) => entry.rules.length > 0)
    .sort(([a, x], [b, y]) => x.order - y.order || (a < b ? -1 : a > b ? 1 : 0));
  for (const [query, entry] of scopedBlocks) {
    if (query.startsWith("[")) {
      blocks.push(...entry.rules);
      continue;
    }
    const body = entry.rules.map((rule) => indent(rule)).join("\n\n");
    blocks.push(`${query} {\n${body}\n}`);
  }

  const hoverRules: string[] = [];
  for (const element of elements) {
    if (element.hover.length > 0) hoverRules.push(hoverRule(element));
    for (const state of element.states ?? []) {
      if (state.state === "hovered") hoverRules.push(cssRule(state.selector, toDeclarations(state.declarations)));
    }
  }
  if (hoverRules.length > 0) {
    blocks.push(mediaBlock("(hover: hover) and (pointer: fine)", hoverRules));
  }

  // kadam 0.3 interaction states, in element then source order.
  for (const element of elements) {
    for (const state of element.states ?? []) {
      if (state.state !== "hovered") blocks.push(cssRule(state.selector, toDeclarations(state.declarations)));
    }
  }

  // kadam 0.3 at-rule wrapped rules (scroll entrances), grouped by at-rule.
  const atRules = new Map<string, string[]>();
  for (const element of elements) {
    for (const rule of element.rules ?? []) {
      if (rule.at === null) continue;
      const list = atRules.get(rule.at) ?? [];
      list.push(cssRule(rule.selector, toDeclarations(rule.declarations)));
      atRules.set(rule.at, list);
    }
  }
  for (const [at, rules] of atRules) {
    blocks.push(`${at} {\n${rules.map((rule) => indent(rule)).join("\n\n")}\n}`);
  }

  // kadam 0.3 looping animations used on this page.
  const loops = new Set(elements.flatMap((element) => element.loops ?? []));
  for (const name of Object.keys(LOOP_KEYFRAMES)) {
    if (!loops.has(name)) continue;
    blocks.push(keyframes(`kdm-loop-${name}`, LOOP_KEYFRAMES[name]!.frames));
  }
  // F8: scroll-driven keyframes this page uses.
  for (const name of Object.keys(SCROLL_KEYFRAMES)) {
    const used = elements.some((element) => (element.rules ?? []).some((rule) => rule.declarations.some((d) => d.property === "animation" && d.value.startsWith(`${name} `))));
    if (used) blocks.push(keyframes(name, SCROLL_KEYFRAMES[name]!));
  }

  const reducedMotionRules: string[] = [];
  for (const element of elements) {
    const wrapper: Declaration[] = [];
    const animated = (element.loops?.length ?? 0) > 0;
    const transitions = element.hover.length > 0 || (element.stateTransitions?.length ?? 0) > 0;
    if (element.motion !== null || animated) wrapper.push(["animation", "none"]);
    if (transitions && !isFieldKind(element)) {
      wrapper.push(["transition", "none"]);
    }
    if (wrapper.length > 0) {
      reducedMotionRules.push(cssRule(`.${element.className}`, wrapper));
    }
    for (const rule of element.rules ?? []) {
      if (rule.reducedMotion && rule.selector !== `.${element.className}`) {
        reducedMotionRules.push(cssRule(rule.selector, [["animation", "none"]]));
      } else if (rule.reducedMotion && element.motion === null && !animated) {
        reducedMotionRules.push(cssRule(rule.selector, [["animation", "none"]]));
      }
    }
    if (isFieldKind(element) && transitions) {
      reducedMotionRules.push(
        cssRule(`.${element.className} .kdm-field-input`, [["transition", "none"]]),
      );
    }
  }
  // D-50: the highlight shows at once, and pages come in without moving.
  if (flatten(page.elements).some((element) => (element.text?.segments ?? []).some((segment) => segment.type === "highlight"))) {
    reducedMotionRules.push(cssRule(".kdm-highlight", [["animation", "none"]]));
  }
  if (page.meta?.enter !== undefined) reducedMotionRules.push(cssRule("body", [["animation", "none"]]));
  if (page.meta?.transition === "cross-fade") {
    reducedMotionRules.push(cssRule("::view-transition-group(*),\n::view-transition-old(*),\n::view-transition-new(*)", [["animation", "none !important"]]));
  }
  if (reducedMotionRules.length > 0) {
    blocks.push(
      mediaBlock("(prefers-reduced-motion: reduce)", reducedMotionRules),
    );
  }

  // kadam 0.3 (F4 step 2): what the runtime hides, last so nothing overrides it.
  blocks.push(...runtimeCssBlocks(page, breakpointQuery));

  return `${blocks.join("\n\n")}\n`;
}

/**
 * kadam 0.3 theme colors and dark mode (D-38): custom properties on :root, the
 * page's dark background and text, and the built-in dark palette. They come
 * before every element rule, so colors the author wrote always win.
 */
function themeBlocks(page: PageIR): string[] {
  const blocks: string[] = [];
  const tokens = page.colorTokens ?? [];
  const style = page.pageStyle;
  const rootLight: Declaration[] = tokens.map((token) => [`--kdm-color-${token.name}`, token.light]);
  if (style.autoDark === true) rootLight.unshift(["color-scheme", "light dark"]);
  if (rootLight.length > 0) blocks.push(cssRule(":root", rootLight));

  const dark: string[] = [];
  const rootDark: Declaration[] = tokens.flatMap((token): Declaration[] =>
    token.dark === null ? [] : [[`--kdm-color-${token.name}`, token.dark]],
  );
  if (rootDark.length > 0) dark.push(cssRule(":root", rootDark));
  const auto = style.autoDark === true;
  const background = style.dark?.background?.value ?? (auto && !style.authored.background ? DARK_PAGE_BACKGROUND : null);
  const text = style.dark?.text?.value ?? (auto && !style.authored.text ? DARK_PAGE_TEXT : null);
  if (background !== null) dark.push(cssRule("body", [["background-color", background]]));
  if (text !== null) {
    dark.push(cssRule(hasPageLandmarks(page) ? ".kdm-page,\n.kdm-page-landmark" : ".kdm-page", [["color", text]]));
  }
  if (auto) {
    const used = new Set(flatten(page.elements).map((element) => element.kind));
    for (const rule of DARK_RULES) {
      if (rule.kinds === "always" || rule.kinds.some((kind) => used.has(kind))) {
        dark.push(cssRule(rule.selector, rule.declarations));
      }
    }
  }
  if (dark.length > 0) blocks.push(mediaBlock("(prefers-color-scheme: dark)", dark));
  return blocks;
}

function baseRules(element: IrElement): readonly string[] {
  if (isFieldKind(element)) {
    return fieldBaseRules(element);
  }

  const declarations: Declaration[] = [];
  appendBoxDeclarations(declarations, element.authored, element.style);
  appendTypographyDeclarations(
    declarations,
    element.authored,
    element.style.typography,
  );
  appendLayoutDeclarations(declarations, element.authored, element.style);
  appendF2Declarations(declarations, element.authored);
  if (needsTransformBox(element)) {
    declarations.push(["display", "inline-block"]);
  }
  if (element.authored.visibility !== undefined) {
    declarations.push(["display", "none"]);
  }
  appendTransition(declarations, element.hover, element.stateTransitions);
  appendMotion(declarations, element.motion);

  return declarations.length === 0
    ? []
    : [cssRule(`.${element.className}`, declarations)];
}

function fieldBaseRules(element: IrElement): readonly string[] {
  const field = element.style.field;
  if (field === null) return [];

  const wrapper: Declaration[] = [];
  if (element.authored.width !== undefined) {
    wrapper.push(["width", formatSize(element.authored.width)]);
  }
  appendSides(wrapper, "margin", element.authored.margin);
  if (element.authored.fontFamily !== undefined) {
    wrapper.push(["font-family", FONT_STACKS[element.authored.fontFamily]]);
  }
  appendF2Declarations(wrapper, element.authored, "wrapper");
  if (element.authored.visibility !== undefined) {
    wrapper.push(["display", "none"]);
  }
  appendMotion(wrapper, element.motion);

  const input: Declaration[] = [];
  if (element.authored.height !== undefined) {
    input.push(["height", formatSize(element.authored.height)]);
  }
  appendBackground(input, element.authored, field.background);
  appendBorder(input, element.authored.border, field.border);
  appendCorners(input, element.authored.corners, field.corners);
  appendShadow(input, element.authored.shadow, field.shadow);
  appendSides(input, "padding", element.authored.padding);
  appendTypographyDeclarations(
    input,
    element.authored,
    field.input,
  );
  appendF2Declarations(input, element.authored, "input");
  appendTransition(input, element.hover, element.stateTransitions);

  const rules: string[] = [];
  if (wrapper.length > 0) {
    rules.push(cssRule(`.${element.className}`, wrapper));
  }
  if (input.length > 0) {
    rules.push(cssRule(`.${element.className} .kdm-field-input`, input));
  }
  return rules;
}

function responsiveRules(
  element: IrElement,
  authored: IrAuthoredStyle,
  style: IrComputedStyle,
): readonly string[] {
  if (isFieldKind(element)) {
    const field = style.field as IrFieldStyle | null;
    if (field === null) return [];
    const wrapper: Declaration[] = [];
    if (authored.width !== undefined) {
      wrapper.push(["width", formatSize(authored.width)]);
    }
    appendSides(wrapper, "margin", authored.margin);
    if (authored.fontFamily !== undefined) {
      wrapper.push(["font-family", FONT_STACKS[authored.fontFamily]]);
    }
    appendF2Declarations(wrapper, authored, "wrapper");
    if (authored.visibility !== undefined) {
      wrapper.push(["display", "none"]);
    }

    const input: Declaration[] = [];
    if (authored.height !== undefined) {
      input.push(["height", formatSize(authored.height)]);
    }
    appendBackground(input, authored, field.background);
    appendBorder(input, authored.border, field.border);
    appendCorners(input, authored.corners, field.corners);
    appendShadow(input, authored.shadow, field.shadow);
    appendSides(input, "padding", authored.padding);
    appendTypographyDeclarations(input, authored, field.input);
    appendF2Declarations(input, authored, "input");

    const rules: string[] = [];
    if (wrapper.length > 0) {
      rules.push(cssRule(`.${element.className}`, wrapper));
    }
    if (input.length > 0) {
      rules.push(cssRule(`.${element.className} .kdm-field-input`, input));
    }
    return rules;
  }

  const declarations: Declaration[] = [];
  appendBoxDeclarations(declarations, authored, style);
  appendTypographyDeclarations(declarations, authored, style.typography);
  appendLayoutDeclarations(declarations, authored, style);
  appendF2Declarations(declarations, authored);
  if (authored.visibility !== undefined) {
    declarations.push(["display", "none"]);
  }

  return declarations.length === 0
    ? []
    : [cssRule(`.${element.className}`, declarations)];
}

function appendBoxDeclarations(
  declarations: Declaration[],
  authored: IrAuthoredStyle,
  style: IrComputedStyle,
): void {
  if (authored.width !== undefined) {
    declarations.push(["width", formatSize(authored.width)]);
  }
  if (authored.height !== undefined) {
    declarations.push(["height", formatSize(authored.height)]);
  }
  appendBackground(declarations, authored, style.background);
  appendBorder(declarations, authored.border, style.border);
  appendCorners(declarations, authored.corners, style.corners);
  appendShadow(declarations, authored.shadow, style.shadow);
  appendSides(declarations, "padding", authored.padding);
  appendSides(declarations, "margin", authored.margin);
}

function appendBackground(
  declarations: Declaration[],
  authored: IrAuthoredStyle,
  background: IrBackground,
): void {
  if (authored.background === undefined && authored.gradientDirection !== true) {
    return;
  }
  switch (background.kind) {
    case "none":
      declarations.push(["background-color", "transparent"]);
      declarations.push(["background-image", "none"]);
      return;
    case "solid":
      declarations.push(["background-color", formatColor(background.color)]);
      declarations.push(["background-image", "none"]);
      return;
    case "gradient":
      declarations.push(["background-color", "transparent"]);
      declarations.push([
        "background-image",
        `linear-gradient(${gradientDirection(background.direction)}, ${formatColor(
          background.from,
        )}, ${formatColor(background.to)})`,
      ]);
      return;
  }
}

function appendBorder(
  declarations: Declaration[],
  authored: IrBorder | undefined,
  border: IrBorder,
): void {
  if (authored === undefined) return;
  if (border.kind === "none") {
    declarations.push(["border", "0"]);
    return;
  }
  declarations.push([
    "border",
    `${formatLength(border.width)} solid ${formatColor(border.color)}`,
  ]);
}

function appendCorners(
  declarations: Declaration[],
  authored: IrCorners | undefined,
  corners: IrCorners,
): void {
  if (authored === undefined) return;
  switch (corners.kind) {
    case "none":
      declarations.push(["border-radius", "0"]);
      return;
    case "length":
      declarations.push(["border-radius", formatLength(corners.value)]);
      return;
    case "pill":
      declarations.push(["border-radius", "9999px"]);
      return;
  }
}

function appendShadow(
  declarations: Declaration[],
  authored: IrElement["authored"]["shadow"],
  shadow: IrElement["style"]["shadow"],
): void {
  if (authored === undefined) return;
  declarations.push([
    "box-shadow",
    shadow === "none" ? "none" : SHADOW_VALUES[shadow],
  ]);
}

function appendSides(
  declarations: Declaration[],
  property: "padding" | "margin",
  sides: Partial<Record<"top" | "right" | "bottom" | "left", IrLength>> | undefined,
): void {
  if (sides === undefined) return;
  for (const side of ["top", "right", "bottom", "left"] as const) {
    const value = sides[side];
    if (value !== undefined) {
      declarations.push([`${property}-${side}`, formatLength(value)]);
    }
  }
}

function appendTypographyDeclarations(
  declarations: Declaration[],
  authored: IrAuthoredStyle,
  typography: IrTypography | null,
): void {
  appendTypographyPresets(declarations, authored, typography);
  if (typography === null) return;
  for (const property of authored.properties ?? []) {
    declarations.push([property.css, formatLength(property.value)]);
  }
}

function appendTypographyPresets(
  declarations: Declaration[],
  authored: IrAuthoredStyle,
  typography: IrTypography | null,
): void {
  // `the font is monospace` on a text element (fields write it on their wrapper).
  if (authored.fontFamily !== undefined && typography !== null) {
    declarations.push(["font-family", FONT_STACKS[authored.fontFamily]]);
  }
  const selected = authored.typography;
  if (selected === undefined || typography === null) return;
  if (selected.fontSize !== undefined) {
    declarations.push(["font-size", formatLength(typography.fontSize)]);
  }
  if (selected.fontWeight !== undefined) {
    declarations.push(["font-weight", String(typography.fontWeight)]);
  }
  if (selected.fontStyle !== undefined) {
    declarations.push(["font-style", typography.fontStyle]);
  }
  if (selected.textAlign !== undefined) {
    declarations.push(["text-align", typography.textAlign]);
  }
  if (selected.color !== undefined) {
    declarations.push(["color", formatColor(typography.color)]);
  }
}

function appendLayoutDeclarations(
  declarations: Declaration[],
  authored: IrAuthoredStyle,
  style: IrComputedStyle,
): void {
  const authoredLayout = authored.layout;
  if (authoredLayout === undefined || style.layout === null) return;

  const direction = style.layout.direction;
  if (authoredLayout.direction !== undefined) {
    declarations.push(["flex-direction", direction]);
    declarations.push([
      axisProperty(direction, "horizontal"),
      alignmentValue(style.layout.horizontal),
    ]);
    declarations.push([
      axisProperty(direction, "vertical"),
      alignmentValue(style.layout.vertical),
    ]);
  } else {
    if (authoredLayout.horizontal !== undefined) {
      declarations.push([
        axisProperty(direction, "horizontal"),
        alignmentValue(style.layout.horizontal),
      ]);
    }
    if (authoredLayout.vertical !== undefined) {
      declarations.push([
        axisProperty(direction, "vertical"),
        alignmentValue(style.layout.vertical),
      ]);
    }
  }
  if (authoredLayout.gap !== undefined && style.gap !== null) {
    declarations.push(["gap", formatLength(style.gap)]);
  }
}

/**
 * kadam 0.3 declarations. On a form field (wrapper plus native input), box
 * and text properties belong to the input, layout properties to the wrapper.
 */
function appendF2Declarations(
  declarations: Declaration[],
  authored: IrAuthoredStyle,
  target: "all" | "wrapper" | "input" = "all",
): void {
  for (const declaration of authored.declarations ?? []) {
    if (target !== "all" && isInputProperty(declaration.property) !== (target === "input")) continue;
    declarations.push([declaration.property, declaration.value]);
  }
}

const INPUT_PROPERTY = /^(?:border|outline|background|box-shadow|color$|font|text-|letter-spacing|line-height|-webkit-backdrop|backdrop)/;

function isInputProperty(property: string): boolean {
  return INPUT_PROPERTY.test(property);
}

function toDeclarations(declarations: readonly IrDeclaration[]): Declaration[] {
  return declarations.map((declaration) => [declaration.property, declaration.value]);
}

function appendTransition(
  declarations: Declaration[],
  hover: readonly IrHoverEffect[],
  states: readonly IrTransition[] = [],
): void {
  if (hover.length === 0 && states.length === 0) return;
  const parts = hover.map((effect) => `${effect.property} ${formatDuration(effect.duration)} ease-out`);
  for (const state of states) {
    // A property already transitioned for hover keeps its hover timing.
    if (hover.some((effect) => effect.property === state.property)) continue;
    parts.push(`${state.property} ${state.duration} ease-out`);
  }
  declarations.push(["transition", parts.join(", ")]);
}

function appendMotion(
  declarations: Declaration[],
  motion: IrMotion | null,
): void {
  if (motion === null) return;
  declarations.push([
    "animation",
    `${motionKeyframe(motion)} ${formatDuration(motion.duration)} ease-out both`,
  ]);
}

/**
 * Inline boxes are not transformable. A link needs a transformable display when
 * its authored lift, scale, or slide would otherwise be silently ignored.
 */
function needsTransformBox(element: IrElement): boolean {
  if (element.kind !== "link") return false;
  if (element.motion !== null && element.motion.effect === "slide") return true;
  return element.hover.some(
    (effect) => effect.property === "translate" || effect.property === "scale",
  );
}

function hoverRule(element: IrElement): string {
  const selector =
    isFieldKind(element)
      ? `.${element.className}:hover .kdm-field-input`
      : `.${element.className}:hover`;
  const declarations: Declaration[] = [];

  for (const effect of element.hover) {
    switch (effect.property) {
      case "background-color":
        declarations.push(["background-color", formatColor(effect.color)]);
        break;
      case "color":
        declarations.push(["color", formatColor(effect.color)]);
        break;
      case "border-color":
        declarations.push(["border-color", formatColor(effect.color)]);
        break;
      case "translate":
        declarations.push([
          "translate",
          `0 ${formatLength({ value: -effect.distance.value, unit: effect.distance.unit })}`,
        ]);
        break;
      case "scale":
        declarations.push([
          "scale",
          formatNumber(effect.percentage / 100),
        ]);
        break;
    }
  }

  return cssRule(selector, declarations);
}

function motionKeyframe(motion: IrMotion): string {
  if (motion.effect === "fade") return "kdm-fade-in";
  return `kdm-slide-in-${motion.direction ?? "bottom"}`;
}

function breakpointQuery(
  breakpoint: "phones" | "tablets" | "desktops",
): string {
  switch (breakpoint) {
    case "phones":
      return "(max-width: 599px)";
    case "tablets":
      return "(min-width: 600px) and (max-width: 1023px)";
    case "desktops":
      return "(min-width: 1024px)";
  }
}

function cssRule(selector: string, declarations: readonly Declaration[]): string {
  const lines = [`${selector} {`];
  for (const [property, value] of declarations) {
    lines.push(`  ${property}: ${value};`);
  }
  lines.push("}");
  return lines.join("\n");
}

function mediaBlock(condition: string, rules: readonly string[]): string {
  const body = rules.map((rule) => indent(rule)).join("\n\n");
  return `@media ${condition} {\n${body}\n}`;
}

function keyframes(
  name: string,
  frames: readonly (readonly [string, readonly Declaration[]])[],
): string {
  const lines = [`@keyframes ${name} {`];
  for (const [frame, declarations] of frames) {
    lines.push(`  ${frame} {`);
    for (const [property, value] of declarations) {
      lines.push(`    ${property}: ${value};`);
    }
    lines.push("  }");
  }
  lines.push("}");
  return lines.join("\n");
}

function indent(value: string): string {
  return value
    .split("\n")
    .map((line) => `  ${line}`)
    .join("\n");
}

function flatten(elements: readonly IrElement[]): readonly IrElement[] {
  const result: IrElement[] = [];
  const visit = (element: IrElement): void => {
    result.push(element);
    for (const child of element.children) visit(child);
  };
  for (const element of elements) visit(element);
  return result;
}

function uniqueByClassName(elements: readonly IrElement[]): readonly IrElement[] {
  const seen = new Set<string>();
  return elements.filter((element) => {
    if (seen.has(element.className)) return false;
    seen.add(element.className);
    return true;
  });
}

function formatSize(size: IrSize): string {
  switch (size.kind) {
    case "auto":
      return "auto";
    case "full":
      return "100%";
    case "length":
      return formatLength(size.value);
  }
}

function formatLength(length: IrLength): string {
  return `${formatNumber(length.value)}${length.unit ?? ""}`;
}

function formatDuration(duration: IrDuration): string {
  return `${formatNumber(duration.value)}${duration.unit}`;
}

function formatColor(color: { readonly value: string }): string {
  return color.value;
}

function gradientDirection(
  direction: "left to right" | "right to left" | "top to bottom" | "bottom to top",
): string {
  switch (direction) {
    case "left to right":
      return "to right";
    case "right to left":
      return "to left";
    case "top to bottom":
      return "to bottom";
    case "bottom to top":
      return "to top";
  }
}

function axisProperty(
  direction: "row" | "column",
  axis: "horizontal" | "vertical",
): "justify-content" | "align-items" {
  if (direction === "row") {
    return axis === "horizontal" ? "justify-content" : "align-items";
  }
  return axis === "horizontal" ? "align-items" : "justify-content";
}

function alignmentValue(value: "start" | "center"): "flex-start" | "center" {
  return value === "center" ? "center" : "flex-start";
}

function formatNumber(value: number): string {
  if (Number.isInteger(value)) return String(value);
  const text = String(value);
  if (!text.includes("e") && !text.includes("E")) return text;
  return value
    .toFixed(12)
    .replace(/0+$/, "")
    .replace(/\.$/, "");
}
