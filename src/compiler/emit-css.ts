/** True when emit-html moves a leading header or trailing footer outside <main>. */
export function hasPageLandmarks(page: PageIR): boolean {
  const elements = page.elements;
  return (
    (elements.length > 0 && elements[0]!.kind === "header") ||
    (elements.length > 0 && elements[elements.length - 1]!.kind === "footer")
  );
}

/** Kinds whose authored box and typography styles target the inner control. */
function isFieldKind(element: IrElement): boolean {
  return element.kind === "text field" || element.kind === "text area" || element.kind === "dropdown";
}

/** Base rules for kadam 0.3 kinds, in catalogue order, only for used kinds. */
export interface BaseCssUsage {
  readonly kinds: ReadonlySet<BuiltinKindName>;
  /** Any text uses an inline link span. */
  readonly inlineLinks: boolean;
}

const EMPTY_USAGE: BaseCssUsage = { kinds: new Set(), inlineLinks: false };

/** What the given pages use, for `emitBaseCss`. */
export function baseCssUsage(pages: readonly PageIR[]): BaseCssUsage {
  const kinds = new Set<BuiltinKindName>();
  let inlineLinks = false;
  const visit = (element: IrElement): void => {
    kinds.add(element.kind);
    if (element.text?.segments?.some((segment) => segment.type === "link") === true) inlineLinks = true;
    element.children.forEach(visit);
  };
  for (const page of pages) page.elements.forEach(visit);
  return { kinds, inlineLinks };
}

