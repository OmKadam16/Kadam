import { emitBaseCss, baseCssUsage, emitPageCss } from "./emit-css.js";
import { emitFragmentHtml, escapeAttribute } from "./emit-html.js";
import { emitNoscriptCss, emitRuntimeJs } from "./emit-js.js";
import type { PageIR } from "./ir.js";
import type { OutputFile } from "./compile.js";
import { assetUrl } from "./routes.js";

/**
 * kadam 0.3 (F6, D-43): fragments. Each page becomes markup for an existing
 * page or CMS, plus one stylesheet whose page-wide rules are scoped to the
 * fragment's wrapper, so it never restyles the host page.
 */

const WRAPPER = ".kdm-fragment";

/** The fragment files for built pages; `assets` are the site's copied files (images, stylesheets, externals). */
export function fragmentFiles(pages: readonly PageIR[], assets: readonly OutputFile[]): OutputFile[] {
  const files: OutputFile[] = [];
  for (const page of pages) {
    const css = `assets/kadam.${page.routeSlug}.fragment.css`;
    const tags = [
      ...(page.stylesheets ?? []).map((href) => `<link rel="stylesheet" href="${escapeAttribute(href)}">`),
      `<link rel="stylesheet" href="${escapeAttribute(assetUrl(css, page.basePath ?? ""))}">`,
    ];
    if (page.runtime !== undefined) {
      const noscript = `assets/kadam.${page.routeSlug}.fragment.noscript.css`;
      tags.push(
        `<script type="module" src="${escapeAttribute(assetUrl(page.runtime.script, page.basePath ?? ""))}"></script>`,
        `<noscript><link rel="stylesheet" href="${escapeAttribute(assetUrl(noscript, page.basePath ?? ""))}"></noscript>`,
      );
      files.push(
        { path: page.runtime.script, contents: emitRuntimeJs(page.runtime), kind: "js" },
        { path: noscript, contents: scopeCss(emitNoscriptCss(page)), kind: "css" },
      );
    }
    files.push(
      { path: `fragments/${page.routeSlug}.html`, contents: emitFragmentHtml(page, tags), kind: "html" },
      { path: css, contents: `${scopeCss(emitBaseCss(baseCssUsage([page])))}\n${scopeCss(emitPageCss(page))}`, kind: "css" },
    );
  }
  files.push(...assets);
  return files.sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0));
}

/**
 * Scope Kadam's own CSS to the wrapper. The input is generated by Kadam, so
 * a small block reader is enough: `body`, `html` and `:root` become the
 * wrapper, other selectors without a Kadam class get the wrapper in front,
 * and @keyframes and @font-face are copied unchanged.
 */
export function scopeCss(css: string, selector: (selector: string) => string = scopeSelector): string {
  let out = "";
  let index = 0;
  while (index < css.length) {
    const open = css.indexOf("{", index);
    if (open === -1) {
      out += css.slice(index);
      break;
    }
    // Comments and whitespace before the prelude stay as they are.
    let start = index;
    let prelude = css.slice(start, open);
    const comment = prelude.lastIndexOf("*/");
    if (comment !== -1) {
      out += prelude.slice(0, comment + 2);
      start += comment + 2;
      prelude = css.slice(start, open);
    }
    const close = matchingBrace(css, open);
    const body = css.slice(open + 1, close);
    const lead = prelude.match(/^\s*/)![0];
    const head = prelude.trim();
    if (head.startsWith("@media") || head.startsWith("@supports") || head.startsWith("@container") || head.startsWith("@layer")) {
      out += `${lead}${head} {${scopeCss(body, selector)}}`;
    } else if (head.startsWith("@")) {
      out += `${lead}${head} {${body}}`;
    } else {
      const trailing = prelude.slice(lead.length + head.length);
      out += `${lead}${scopeSelectors(head, selector)}${trailing}{${body}}`;
    }
    index = close + 1;
  }
  return out;
}

function matchingBrace(css: string, open: number): number {
  let depth = 0;
  for (let index = open; index < css.length; index += 1) {
    if (css[index] === "{") depth += 1;
    else if (css[index] === "}") {
      depth -= 1;
      if (depth === 0) return index;
    }
  }
  return css.length;
}

function scopeSelectors(list: string, scope: (selector: string) => string): string {
  const parts = list.split(",");
  const scoped: string[] = [];
  for (const part of parts) {
    const space = part.match(/^\s*/)![0];
    const selector = part.trim();
    const result = scope(selector);
    if (!scoped.some((item) => item.trim() === result)) scoped.push(`${space}${result}`);
  }
  return scoped.join(",");
}

function scopeSelector(selector: string): string {
  const root = selector.match(/^(html|body|:root)(?=$|[\s.[:>])/);
  if (root !== null) return `${WRAPPER}${selector.slice(root[1]!.length)}`;
  // Kadam classes and element ids are already unique to Kadam output.
  if (/^[a-z]*\.kdm-/.test(selector) || selector.startsWith("[data-kdm-id")) return selector;
  return `${WRAPPER} ${selector}`;
}
