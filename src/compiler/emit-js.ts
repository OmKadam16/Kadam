import type { IrElement, PageIR } from "./ir.js";
import type { IrEffect, IrRuntime } from "./lower-f4.js";

/**
 * kadam 0.3 (F4 step 2, D-36): the page runtime. Each page that needs one gets
 * its own module, written from the features it uses: the data tables hold only
 * this page's elements and state, and the interpreter holds only the effect
 * kinds this page uses. No eval, no new Function, no innerHTML, and no inline
 * handlers, so `script-src 'self'` works.
 */

const HEADER = "// Generated by Kadam. Do not edit.";

export function runtimeScriptPath(page: PageIR): string | null {
  return page.runtime?.script ?? null;
}

export function noscriptStylesheetPath(page: PageIR): string | null {
  return page.runtime === undefined ? null : page.runtime.script.replace(/\.js$/, ".noscript.css");
}

export function emitRuntimeJs(runtime: IrRuntime): string {
  const effects = new Set<IrEffect["type"]>(runtime.handlers.flatMap((handler) => handler.effects.map((effect) => effect.type)));
  const usesState = runtime.states.length > 0;
  const lines: string[] = [HEADER, "", "const nodes = new Map();", 'for (const node of document.querySelectorAll("[data-kdm-id]")) nodes.set(node.getAttribute("data-kdm-id"), node);', ""];

  if (usesState) lines.push(`const state = new Map(${json(runtime.states.map((s) => [s.key, s.initial]))});`);
  const addressed = runtime.addressed.length > 0;
  if (addressed) lines.push(`const addressed = ${json(runtime.addressed)};`, ...ADDRESS_JS);
  if (runtime.textBindings.length > 0) lines.push(`const texts = ${json(runtime.textBindings.map((b) => [b.nodeId, b.key]))};`);
  if (runtime.visibilityBindings.length > 0) {
    lines.push(`const shown = ${json(runtime.visibilityBindings.map((b) => [b.nodeId, b.key, b.value, b.attribute]))};`);
  }
  if (runtime.controllers.length > 0) {
    lines.push(`const controllers = ${json(runtime.controllers.map((c) => [c.nodeId, c.targets, c.key]))};`);
  }
  lines.push(`const handlers = ${json(runtime.handlers.map((h) => [h.nodeId, h.trigger === "click" ? "click" : h.key, h.effects.map(compactEffect)]))};`);
  const loads = runtime.loaders.length > 0;
  if (loads) {
    lines.push(
      `const loaders = ${json(runtime.loaders.map((l) => [l.source, l.url, l.nodeId, l.fields, l.loading, l.empty, l.error, l.lists.map((list) => [list.template, list.filters, list.sort, list.limit, list.paging])]))};`,
    );
  }
  lines.push("");

  // render(): bindings and aria-expanded follow state and visibility.
  const render: string[] = [];
  if (runtime.textBindings.length > 0) {
    render.push("  for (const [id, key] of texts) nodes.get(id).textContent = String(state.get(key));");
  }
  if (runtime.visibilityBindings.length > 0) {
    render.push("  for (const [id, key, value, attribute] of shown) nodes.get(id).toggleAttribute(attribute, state.get(key) !== value);");
  }
  if (runtime.controllers.length > 0) {
    render.push(
      "  for (const [id, targets, key] of controllers) {",
      '    const open = key === null ? targets.every((target) => !nodes.get(target).hasAttribute("data-kdm-hidden")) : state.get(key) === true;',
      '    nodes.get(id).setAttribute("aria-expanded", String(open));',
      "  }",
    );
  }
  lines.push("function render() {", ...render, "}", "");

  if (effects.has("open-dialog")) {
    lines.push(
      "function openDialog(dialog) {",
      "  if (dialog.open) return;",
      "  const opener = document.activeElement;",
      '  dialog.addEventListener("close", () => { if (opener instanceof HTMLElement && opener.isConnected) opener.focus(); }, { once: true });',
      "  dialog.showModal();",
      "}",
      "",
    );
  }
  if (effects.has("focus")) {
    lines.push(
      "function focusNode(node) {",
      '  if (!node.matches("a[href], button, input, select, textarea, summary, [tabindex]")) node.setAttribute("tabindex", "-1");',
      "  node.focus();",
      "}",
      "",
    );
  }

  if (loads) lines.push(...LOADER_JS, "");

  const cases: string[] = [];
  if (effects.has("visibility")) {
    cases.push(
      '      case "show": nodes.get(effect[1]).removeAttribute("data-kdm-hidden"); break;',
      '      case "hide": nodes.get(effect[1]).setAttribute("data-kdm-hidden", ""); break;',
      '      case "flip": nodes.get(effect[1]).toggleAttribute("data-kdm-hidden"); break;',
    );
  }
  if (effects.has("open-dialog")) cases.push('      case "open": openDialog(nodes.get(effect[1])); break;');
  if (effects.has("close-dialog")) cases.push('      case "close": nodes.get(effect[1]).closest("dialog").close(); break;');
  if (effects.has("focus")) cases.push('      case "focus": focusNode(nodes.get(effect[1])); break;');
  if (effects.has("set")) cases.push('      case "set": state.set(effect[1], effect[2]); break;');
  if (effects.has("flip")) cases.push('      case "toggle": state.set(effect[1], !state.get(effect[1])); break;');
  if (effects.has("add")) cases.push('      case "add": state.set(effect[1], state.get(effect[1]) + effect[2]); break;');
  if (effects.has("reload")) cases.push('      case "reload": load(loaders.find((entry) => entry[0] === effect[1])); break;');
  if (effects.has("tell")) cases.push('      case "tell": nodes.get(effect[1]).dispatchEvent(new CustomEvent(effect[2], { bubbles: true, composed: true })); break;');
  if (effects.has("call")) {
    // F6 (D-42): externals load on first use; an error stays in the console.
    lines.push(
      `const externals = ${json(runtime.externals)};`,
      "function callExternal(effect) {",
      "  const args = effect[3].map((arg) => (arg[0] === 1 ? state.get(arg[1]) : arg[1]));",
      '  import(externals[effect[1]]).then((module) => module[effect[2]](...args)).catch((error) => console.error("kadam: " + effect[2] + " failed", error));',
      "}",
      "",
    );
    cases.push('      case "call": callExternal(effect); break;');
  }
  lines.push(
    "function run(effects) {",
    "  for (const effect of effects) {",
    "    switch (effect[0]) {",
    ...cases,
    "    }",
    "  }",
    "  render();",
    ...(addressed ? ["  writeAddress();"] : []),
    ...(loads ? ["  for (const entry of loaders) showRecords(entry);"] : []),
    "}",
    "",
  );

  if (runtime.controllers.length > 0) {
    lines.push(
      "// Toggles announce what they control only once the runtime has loaded.",
      'for (const [id, targets] of controllers) nodes.get(id).setAttribute("aria-controls", targets.map((target) => nodes.get(target).id).join(" "));',
    );
  }
  const keyed = runtime.handlers.some((handler) => handler.trigger === "key");
  lines.push(
    "for (const [id, trigger, effects] of handlers) {",
    '  if (trigger === "click") nodes.get(id).addEventListener("click", () => run(effects));',
    ...(keyed
      ? ['  else nodes.get(id).addEventListener("keydown", (event) => { if (event.key === trigger && !event.isComposing) run(effects); });']
      : []),
    "}",
    ...(addressed ? ["readAddress();", 'addEventListener("popstate", () => {', "  readAddress();", "  render();", ...(loads ? ["  for (const entry of loaders) showRecords(entry);"] : []), "});"] : []),
    "render();",
    ...(loads ? ["for (const entry of loaders) load(entry);"] : []),
    "",
  );
  return lines.join("\n");
}

function compactEffect(effect: IrEffect): readonly unknown[] {
  switch (effect.type) {
    case "visibility":
      return [effect.mode, effect.target];
    case "open-dialog":
      return ["open", effect.target];
    case "close-dialog":
      return ["close", effect.from];
    case "focus":
      return ["focus", effect.target];
    case "set":
      return ["set", effect.key, effect.value];
    case "flip":
      return ["toggle", effect.key];
    case "add":
      return ["add", effect.key, effect.amount];
    case "reload":
      return ["reload", effect.source];
    case "call":
      return ["call", effect.module, effect.name, effect.args];
    case "tell":
      return ["tell", effect.from, effect.event];
  }
}

function json(value: unknown): string {
  // `<` is escaped so the data can never close a script element, wherever it ends up.
  return JSON.stringify(value).replace(/</g, "\\u003c");
}

/**
 * With JavaScript off, nothing can be shown again, so everything the runtime
 * would hide is shown and dialogs sit in the page flow.
 */
export function emitNoscriptCss(page: PageIR): string {
  const blocks: string[] = ["/* Generated by Kadam. Do not edit. Loaded only when JavaScript is off. */"];
  // kadam 0.3 (D-41): with JavaScript off, data cannot load: show only the error state.
  const loaderStates = new Set((page.runtime?.loaders ?? []).flatMap((loader) => [loader.loading, loader.empty]));
  for (const loader of page.runtime?.loaders ?? []) {
    blocks.push(`[data-kdm-id="${loader.loading}"] {\n  display: none !important;\n}`);
  }
  const visit = (element: IrElement): void => {
    const hidden = (element.attributes ?? []).filter(([name]) => name.startsWith("data-kdm-hidden"));
    if (hidden.length > 0 && element.kind !== "dialog" && !loaderStates.has(element.nodeId)) {
      const selector = `[data-kdm-id="${element.nodeId}"]`;
      blocks.push(`${selector} {\n  display: ${element.style.display} !important;\n}`);
    }
    element.children.forEach(visit);
  };
  page.elements.forEach(visit);
  if (flatten(page.elements).some((element) => element.kind === "dialog")) {
    blocks.push("dialog.kdm-kind-dialog:not([open]) {\n  display: flex !important;\n  position: static;\n  margin: 0;\n}");
  }
  return `${blocks.join("\n\n")}\n`;
}

/** The page CSS rules that hide what the runtime controls. */
export function runtimeCssBlocks(page: PageIR, breakpointQuery: (breakpoint: "phones" | "tablets" | "desktops") => string): string[] {
  const runtime = page.runtime;
  if (runtime === undefined) return [];
  const blocks = ["[data-kdm-hidden] {\n  display: none !important;\n}"];
  for (const breakpoint of runtime.scopes) {
    blocks.push(`@media ${breakpointQuery(breakpoint)} {\n  [data-kdm-hidden-${breakpoint}] {\n    display: none !important;\n  }\n}`);
  }
  return blocks;
}

function flatten(elements: readonly IrElement[]): IrElement[] {
  return elements.flatMap((element) => [element, ...flatten(element.children)]);
}

/**
 * kadam 0.3 (D-41): load JSON with no cookies, check every record against
 * the declared shape, and clone the list's template per record. Values reach
 * the page only through text nodes and checked attributes; a newer request
 * cancels an older one.
 */
const LOADER_JS: readonly string[] = [
  "const FIELD = /https:\\/\\/kadam\\.invalid\\/field\\/(?:text|number|url)\\/([a-z][A-Za-z0-9]{0,63})/g;",
  "const SAFE_URL = /^(?:https?:\\/\\/|mailto:|\\/(?!\\/)|#)/i;",
  "const requests = new Map();",
  "const rendered = new Map();",
  "function validRecord(record, fields) {",
  "  if (typeof record !== \"object\" || record === null || Array.isArray(record)) return false;",
  "  return fields.every(([name, type]) => {",
  "    const value = record[name];",
  "    if (type === \"text\") return typeof value === \"string\";",
  "    if (type === \"number\") return typeof value === \"number\" && Number.isFinite(value);",
  "    if (type === \"yes/no\") return typeof value === \"boolean\";",
  "    return typeof value === \"string\" && SAFE_URL.test(value) && !/[\\u0000-\\u0020]/.test(value);",
  "  });",
  "}",
  "const cached = new Map();",
  "function shapeList(records, [, filters, sort, limit, paging]) {",
  "  let list = records.filter((record) => filters.every(([field, negated, value, key, unless]) => {",
  "    if (key !== null && unless !== null && state.get(key) === unless) return true;",
  "    return (record[field] === (key === null ? value : state.get(key))) !== negated;",
  "  }));",
  "  if (sort !== null) {",
  "    const [field, descending] = sort;",
  "    list = [...list].sort((a, b) => {",
  "      const order = a[field] < b[field] ? -1 : a[field] > b[field] ? 1 : 0;",
  "      return descending ? -order : order;",
  "    });",
  "  }",
  "  if (paging !== null) {",
  "    const page = Math.max(1, Math.floor(state.get(paging[1])) || 1);",
  "    return list.slice((page - 1) * paging[0], page * paging[0]);",
  "  }",
  "  return limit === null ? list : list.slice(0, limit);",
  "}",
  "function fill(root, record) {",
  "  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);",
  "  for (let text = walker.nextNode(); text !== null; text = walker.nextNode()) {",
  "    text.data = text.data.replace(FIELD, (_, name) => String(record[name]));",
  "  }",
  "  for (const node of [root, ...root.querySelectorAll(\"*\")]) {",
  "    node.removeAttribute(\"data-kdm-id\");",
  "    node.removeAttribute(\"id\");",
  "    for (const attribute of [...node.attributes]) {",
  "      if (!attribute.value.includes(\"kadam.invalid\")) continue;",
  "      const isUrl = attribute.name === \"href\" || attribute.name === \"src\";",
  "      const value = attribute.value.replace(FIELD, (_, name, offset) => (isUrl && offset > 0 ? encodeURIComponent(String(record[name])) : String(record[name])));",
  "      if (isUrl && !SAFE_URL.test(value)) node.removeAttribute(attribute.name);",
  "      else node.setAttribute(attribute.name, value);",
  "    }",
  "  }",
  "}",
  "async function load(entry) {",
  "  const [source, url, containerId, fields, loadingId, emptyId, errorId] = entry;",
  "  requests.get(source)?.abort();",
  "  cached.delete(source);",
  "  const controller = new AbortController();",
  "  requests.set(source, controller);",
  "  const show = (id, visible) => nodes.get(id).toggleAttribute(\"data-kdm-hidden\", !visible);",
  "  for (const node of rendered.get(source) ?? []) node.remove();",
  "  rendered.set(source, []);",
  "  show(loadingId, true);",
  "  show(emptyId, false);",
  "  show(errorId, false);",
  "  nodes.get(containerId).setAttribute(\"aria-busy\", \"true\");",
  "  let records = null;",
  "  try {",
  "    const response = await fetch(url, { credentials: \"omit\", signal: controller.signal, headers: { accept: \"application/json\" } });",
  "    const text = response.ok ? await response.text() : \"\";",
  "    if (response.ok && text.length <= 2000000) {",
  "      const data = JSON.parse(text);",
  "      const items = Array.isArray(data) ? data : data !== null && typeof data === \"object\" && Array.isArray(data.items) ? data.items : null;",
  "      if (items !== null && items.length <= 1000 && items.every((record) => validRecord(record, fields))) records = items;",
  "    }",
  "  } catch {",
  "    records = null;",
  "  }",
  "  if (requests.get(source) !== controller) return;",
  "  nodes.get(containerId).removeAttribute(\"aria-busy\");",
  "  show(loadingId, false);",
  "  if (records === null) {",
  "    show(errorId, true);",
  "    return;",
  "  }",
  "  cached.set(source, records);",
  "  showRecords(entry);",
  "}",
  "// Lists follow state (filters, pages) without loading again.",
  "function showRecords([source, , , , , emptyId, , lists]) {",
  "  const records = cached.get(source);",
  "  if (records === undefined) return;",
  "  for (const node of rendered.get(source) ?? []) node.remove();",
  "  rendered.set(source, []);",
  "  let count = 0;",
  "  for (const list of lists) {",
  "    const template = document.querySelector(`template[data-kdm-template=\"${list[0]}\"]`);",
  "    for (const record of shapeList(records, list)) {",
  "      const clone = template.content.firstElementChild.cloneNode(true);",
  "      fill(clone, record);",
  "      template.before(clone);",
  "      rendered.get(source).push(clone);",
  "      count += 1;",
  "    }",
  "  }",
  "  nodes.get(emptyId).toggleAttribute(\"data-kdm-hidden\", count !== 0);",
  "}",
];

/**
 * F5 step 7: states kept in the address. A valid `?name=` value replaces the
 * starting value; a change replaces the address (no new history entry); a
 * value equal to the start leaves the parameter out.
 */
const ADDRESS_JS: readonly string[] = [
  "const starts = new Map(addressed.map(([key]) => [key, state.get(key)]));",
  "function readAddress() {",
  "  const params = new URLSearchParams(location.search);",
  "  for (const [key, name] of addressed) {",
  "    const start = starts.get(key);",
  "    const raw = params.get(name);",
  "    let value = start;",
  "    if (raw !== null) {",
  "      if (typeof start === \"number\") value = raw.trim() !== \"\" && Number.isFinite(Number(raw)) ? Number(raw) : start;",
  "      else if (typeof start === \"boolean\") value = raw === \"true\" ? true : raw === \"false\" ? false : start;",
  "      else value = raw;",
  "    }",
  "    state.set(key, value);",
  "  }",
  "}",
  "function writeAddress() {",
  "  const params = new URLSearchParams(location.search);",
  "  for (const [key, name] of addressed) {",
  "    if (state.get(key) === starts.get(key)) params.delete(name);",
  "    else params.set(name, String(state.get(key)));",
  "  }",
  "  const search = params.toString();",
  "  const next = `${location.pathname}${search === \"\" ? \"\" : `?${search}`}${location.hash}`;",
  "  if (next !== `${location.pathname}${location.search}${location.hash}`) history.replaceState(history.state, \"\", next);",
  "}",
];
