import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";

import { compileText } from "../dist/compiler/compile.js";
import { compileProject } from "../dist/compiler/project.js";

// D-44 step 1: pages load data from typed functions in a kadam 0.2 server module.

const ROOT = "test/fixtures/server-shop";
const MODULE = readFileSync(`${ROOT}/server/shop.kdm`, "utf8");
const PAGE = readFileSync(`${ROOT}/pages/index.kdm`, "utf8");
const MANIFEST = JSON.parse(readFileSync(`${ROOT}/kadam.json`, "utf8"));
const codes = (result) => result.diagnostics.map((d) => d.code);
const file = (result, path) => String(result.files.find((f) => f.path === path)?.contents ?? "");
function build({ module = MODULE, page = PAGE, manifest = MANIFEST } = {}) {
  return compileProject({
    projectRoot: ROOT,
    manifestText: JSON.stringify(manifest),
    sourceOverrides: new Map([["server/shop.kdm", module], ["pages/index.kdm", page]]),
  });
}

test("a server load takes its shape from the function's record", () => {
  const result = build();
  assert.deepEqual(codes(result), []);
  assert.match(file(result, "assets/kadam.home.js"),
    /const loaders = \[\["products","\/_kadam\/listProducts","home-catalog",\[\["name","text"\],\["category","text"\],\["price","number"\],\["inStock","yes\/no"\]\]/);
  // List sentences are checked against the record's fields.
  const typo = build({ page: PAGE.replace("only where the inStock of product", "only where the inStok of product") });
  assert.deepEqual(codes(typo), ["KDM3043"]);
  const wrong = build({ page: PAGE.replace("only where the inStock of product is true", 'only where the price of product is "cheap"') });
  assert.ok(codes(wrong).includes("KDM3043"));
});

test("the build writes the module with an export list and a standard-library server", () => {
  const result = build({ module: MODULE.replace("    function listProducts", "    function secret takes nothing and returns text {\n        return \"hidden\"\n    }\n\n    function listProducts") });
  assert.deepEqual(codes(result), []);
  const module = file(result, "server/shop.ts");
  assert.match(module, /^\/\/ Generated by Kadam target "typescript"/);
  assert.match(module, /export \{ k_listProducts as listProducts, k_signUp as signUp \};\n$/);
  assert.doesNotMatch(module, /k_secret as/);
  const server = file(result, "server/server.ts");
  assert.match(server, /import \* as app from "\.\/shop\.ts";/);
  assert.match(server, /"listProducts": app\.listProducts,\n\};/);
  assert.doesNotMatch(server, /secret/);
  assert.deepEqual([...server.matchAll(/from "([^"]+)"/g)].map((m) => m[1]).filter((s) => !s.startsWith("node:")), ["./shop.ts"]);
  assert.match(server, /"x-content-type-options": "nosniff"/);
});

test("a server load must name a function that takes nothing and returns a list of flat records", () => {
  const messages = (result) => result.diagnostics.map((d) => d.message);
  assert.deepEqual(messages(build({ page: PAGE.replace("server function listProducts", "server function listProdcts") })),
    ["the server module has no function named listProdcts"]);
  assert.match(messages(build({ module: MODULE.replace("listProducts takes nothing", "listProducts takes limit as number") .replace("returns list of Product {", "returns list of Product {\n        output limit") }))[0],
    /takes 1 value; a function a page loads from takes nothing/);
  assert.match(messages(build({ module: MODULE.replace("returns list of Product {", "returns Product {").replace(/return \[(Product \{[^}]*\}).*\]/, "return $1") }))[0],
    /returns Product; a page loads a list of records/);
  const nested = MODULE.replace("        inStock as boolean\n", "        inStock as boolean\n        tags as list of text\n").replace(/inStock: (true|false) \}/g, "inStock: $1, tags: [] }");
  assert.match(messages(build({ module: nested }))[0], /Product\.tags is list of text; loaded records have text, number and boolean fields/);
  const shaped = build({ page: PAGE.replace("        while loading", "        each product has a name as text\n        while loading") });
  assert.deepEqual(codes(shaped), ["KDM3060"]);
});

test("the server module must compile and has no main; its errors stop the build", () => {
  const broken = build({ module: MODULE.replace("price as number", "price as money") });
  assert.ok(codes(broken).every((code) => code.startsWith("KDM5")), codes(broken).join());
  const main = build({ module: MODULE.replace("    function listProducts", "    function main takes nothing and returns number {\n        return 0\n    }\n\n    function listProducts") });
  assert.deepEqual(codes(main), ["KDM3060"]);
});

test("server settings are checked, and a single file has no server", () => {
  assert.ok(codes(build({ manifest: { ...MANIFEST, server: { module: "server/shop.kdm", target: "java" } } })).includes("KDM4001"));
  assert.ok(codes(build({ manifest: { ...MANIFEST, server: { module: "../shop.kdm", target: "typescript" } } })).includes("KDM4001"));
  assert.ok(codes(build({ manifest: { ...MANIFEST, server: { module: "server/missing.kdm", target: "typescript" } } })).includes("KDM4012"));
  const reserved = build({ manifest: { ...MANIFEST, pages: [{ source: "pages/index.kdm", route: "/server" }] } });
  assert.deepEqual(codes(reserved), ["KDM4012"]);
  const single = compileText("index.kdm", PAGE);
  assert.ok(codes(single).includes("KDM3060"));
  // Without a server, the build writes no server files.
  const { server: _server, ...plain } = MANIFEST;
  const noServer = compileProject({ projectRoot: "examples/reference/shop" });
  assert.ok(!noServer.files.some((f) => f.path.startsWith("server/")));
  assert.equal(plain.kadam, "0.3");
});

// D-44 step 2: forms that send to a server function.

test("a server form sends to its function's route and names its states", () => {
  const result = build();
  assert.deepEqual(codes(result), []);
  const html = file(result, "index.html");
  assert.match(html, /<form [^>]*action="\/_kadam\/signUp\?form=home-signupForm" method="post">/);
  assert.match(html, /data-kdm-id="home-thanksNote" data-kdm-hidden role="status"/);
  assert.match(html, /data-kdm-id="home-sorryNote" data-kdm-hidden role="alert"/);
  assert.match(file(result, "assets/kadam.home.js"), /const forms = \[\["home-signupForm","home-thanksNote","home-sorryNote","signUp"\]\];/);
  // Without JavaScript the server shows a state, so neither is shown up front.
  assert.doesNotMatch(file(result, "assets/kadam.home.noscript.css"), /thanksNote|sorryNote/);
  const server = file(result, "server/server.ts");
  assert.match(server, /"signUp": \{ call: app\.signUp as \(value: never\) => void, fields: \[\["address","text"\],\["plan","text"\],\["news","boolean"\]\] \},/);
  assert.match(server, /"home-signupForm": \["index\.html","home-thanksNote","home-sorryNote"\],/);
  assert.match(file(result, "server/shop.ts"), /export \{ k_listProducts as listProducts, k_signUp as signUp \};/);
});

test("form controls must be exactly the record's fields, with matching types", () => {
  const messages = (result) => result.diagnostics.map((d) => d.message);
  assert.deepEqual(messages(build({ page: PAGE.replace("        news {\n            a checkbox", "        newsletter {\n            a checkbox") })), [
    "Signup has a field news, but signupForm has no control named news",
    "signupForm sends newsletter, but Signup has no field newsletter",
  ]);
  assert.deepEqual(messages(build({ module: MODULE.replace("news as boolean", "news as text") })),
    ["news is text in Signup, so it needs a text field, text area, dropdown, or radio group"]);
  assert.deepEqual(messages(build({ module: MODULE.replace("plan as text", "plan as boolean").replace('" (" + signup.plan + ")"', '"!"') })),
    ["plan is boolean in Signup, so it needs a checkbox"]);
  assert.match(messages(build({ module: MODULE.replace("plan as text", "plan as number").replace('" (" + signup.plan + ")"', '"!"') }))[0],
    /Signup\.plan is number; a form sends text and boolean fields/);
});

test("a server form needs a function taking one record and returning nothing, and both states", () => {
  const messages = (result) => result.diagnostics.map((d) => d.message);
  assert.deepEqual(messages(build({ page: PAGE.replace("server function signUp", "server function signUpp") })), ["the server module has no function named signUpp"]);
  assert.match(messages(build({ page: PAGE.replace("server function signUp", "server function listProducts") }))[0], /takes one record and returns nothing; listProducts does not/);
  assert.deepEqual(messages(build({ page: PAGE.replace("        when sending fails, it shows sorryNote\n", "") })), ["signupForm sends to signUp but has no failed state"]);
  assert.deepEqual(codes(build({ page: PAGE.replace("when sending fails, it shows sorryNote", "when sending fails, it shows intro") })), ["KDM3012"]);
  assert.deepEqual(codes(build({ page: PAGE.replace("when sending fails, it shows sorryNote", "when sending fails, it shows thanksNote") })), ["KDM3061"]);
  const urlForm = PAGE.replace("it sends to the server function signUp", 'it sends to "https://example.com/signup"');
  assert.deepEqual(messages(build({ page: urlForm })), [
    "sent and failed states are for a form that sends to a server function",
    "sent and failed states are for a form that sends to a server function",
  ]);
  assert.ok(codes(compileText("index.kdm", PAGE)).includes("KDM3061"));
});

// D-44 step 4: the Python target.

test("target python writes the module and a standard-library WSGI server", () => {
  const result = build({ manifest: { ...MANIFEST, server: { module: "server/shop.kdm", target: "python" } } });
  assert.deepEqual(codes(result), []);
  assert.deepEqual(result.files.filter((f) => f.path.startsWith("server/")).map((f) => [f.path, f.kind]), [["server/server.py", "server"], ["server/shop.py", "server"]]);
  const server = file(result, "server/server.py");
  assert.match(file(result, "server/shop.py"), /^# Generated by Kadam target "python"/);
  assert.match(server, /^import shop as app {2}# noqa: E402$/m);
  assert.match(server, /"listProducts": app\.k_listProducts,/);
  assert.match(server, /"signUp": \(app\.k_signUp, app\.KadamRecord_Signup, \[\("address", "text"\), \("plan", "text"\), \("news", "boolean"\)\]\),/);
  assert.match(server, /"home-signupForm": \("index\.html", "home-thanksNote", "home-sorryNote"\),/);
  // Only the standard library.
  const imports = [...server.matchAll(/^(?:from (\S+) import|import (\S+))/gm)].map((m) => (m[1] ?? m[2]).split(".")[0]);
  assert.deepEqual([...new Set(imports)].sort(), ["__future__", "dataclasses", "json", "os", "pathlib", "re", "shop", "sys", "traceback", "urllib", "wsgiref"]);
  assert.match(server, /^def application\(environ, start_response\):$/m);
});

test("both targets expose the same functions, and the module cannot be named server", () => {
  for (const target of ["typescript", "python"]) {
    const named = compileProject({
      projectRoot: ROOT,
      manifestText: JSON.stringify({ ...MANIFEST, server: { module: "server/server.kdm", target } }),
      sourceOverrides: new Map([["server/server.kdm", MODULE.replace("module shop {", "module server {")]]),
    });
    assert.deepEqual(named.diagnostics.map((d) => d.message), ["the server module cannot be named server"], target);
  }
  assert.ok(codes(build({ manifest: { ...MANIFEST, server: { module: "server/shop.kdm", target: "rust" } } })).includes("KDM4001"));
});
