import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";

import { compileText } from "../dist/compiler/compile.js";
import { compileProject } from "../dist/compiler/project.js";
import { compileWebComponents, tagName } from "../dist/compiler/web-components.js";

// F6 (D-43): the Web Components target.

const ROOT = "test/fixtures/web-components";
const PANEL = readFileSync(`${ROOT}/components/Panel.kdm`, "utf8");
const codes = (result) => result.diagnostics.map((d) => d.code);
const build = (component, extra = {}) =>
  compileWebComponents({ projectRoot: ROOT, sourceOverrides: new Map([["components/Panel.kdm", component], ...Object.entries(extra)]) });

test("component names become custom element tags", () => {
  assert.equal(tagName("ProductCard", null), "kadam-product-card");
  assert.equal(tagName("Panel", null), "kadam-panel");
  assert.equal(tagName("HTMLBlock", null), "kadam-html-block");
  assert.equal(tagName("Hero", "studio"), "kadam-studio-hero");
});

test("each component becomes one element with its parameters, variants, slots and events", () => {
  const result = compileWebComponents({ projectRoot: ROOT });
  assert.deepEqual(codes(result), []);
  assert.deepEqual(result.elements, [{
    tag: "kadam-panel", component: "Panel", namespace: null,
    parameters: [{ name: "title", type: "text", defaultValue: null }, { name: "link", type: "url", defaultValue: "https://example.com" }],
    variants: ["default", "compact"], events: ["pick"], slots: [null, "footer"],
  }]);
  assert.deepEqual(result.files.map((f) => f.path), ["kadam-elements.js", "kadam-elements.d.ts", "kadam-elements.react.d.ts"]);
  const js = String(result.files[0].contents);
  assert.match(js, /^\/\/ Generated by Kadam\. Do not edit\./);
  assert.match(js, /define\("kadam-panel", \[\["title",""\],\["link","https:\/\/example\.com"\]\], \{"default":/);
  assert.match(js, /\\u003cslot>\\u003c\/slot>/);
  assert.match(js, /\\u003cslot name=\\"footer\\">\\n {2}\\u003cp [^>]*>Default footer/);
  // Page-wide rules apply to :host; nothing is written for a page background.
  assert.match(js, /:host \{\\n {2}color: #171717;/);
  assert.doesNotMatch(js, /kdm-slot-(start|end)|body \{|:root \{/);
  assert.doesNotMatch(js, /eval\(|new Function|\.innerHTML = (?!html)/);
});

test("the same build is deterministic", () => {
  const a = String(compileWebComponents({ projectRoot: ROOT }).files[0].contents);
  const b = String(compileWebComponents({ projectRoot: ROOT }).files[0].contents);
  assert.equal(a, b);
});

test("only text and url parameters can become attributes for now", () => {
  const result = build(PANEL.replace("a link as url", "a picture as image"));
  assert.deepEqual(codes(result), ["KDM3054"]);
  assert.match(result.diagnostics[0].message, /Panel takes picture as image; web components support text and url parameters/);
});

test("components with their own state are refused for now", () => {
  const stateful = PANEL.replace('            when clicked, tell the page "pick"', "            it remembers n, a number that starts as 0\n            when clicked, add 1 to n");
  const result = build(stateful);
  assert.deepEqual(codes(result), ["KDM3055"]);
});

test("tell the page is for components, and dispatches an event in a normal build too", () => {
  const page = compileText("home.kdm", ["kadam 0.3", 'page "Home" {', "    b1 {", "        a button", '        the text says "Go"', '        when clicked, tell the page "go"', "    }", "}", ""].join("\n"));
  assert.deepEqual(codes(page), ["KDM3012"]);
  assert.match(page.diagnostics[0].message, /only used inside a component/);
  const site = compileProject({ projectRoot: ROOT, write: false });
  assert.deepEqual(codes(site), []);
  const js = String(site.files.find((f) => f.path === "assets/kadam.home.js").contents);
  assert.match(js, /case "tell": nodes\.get\(effect\[1\]\)\.dispatchEvent\(new CustomEvent\(effect\[2\], \{ bubbles: true, composed: true \}\)\)/);
  assert.match(js, /\["tell","home-p1-pick1","pick"\]/);
  // Slot markers exist only in the web-components build.
  assert.doesNotMatch(String(site.files.find((f) => f.path === "index.html").contents), /kdm-slot/);
  assert.equal(codes(compileText("x.kdm", ["kadam 0.3", 'page "X" {', "    b1 {", "        a button", '        the text says "Go"', '        when clicked, tell the page "Bad Name"', "    }", "}", ""].join("\n")))[0], "KDM3005");
});

test("the web-components target needs kadam 0.3 and at least one component", () => {
  const old = compileWebComponents({ projectRoot: ROOT, sourceOverrides: new Map([["kadam.json", '{"kadam":"0.1","name":"x","pages":[{"source":"pages/home.kdm","route":"/"}]}']]) });
  assert.ok(codes(old).includes("KDM4001"));
  const none = compileWebComponents({ projectRoot: ROOT, sourceOverrides: new Map([["kadam.json", '{"kadam":"0.3","name":"x","pages":[{"source":"pages/home.kdm","route":"/"}]}']]) });
  assert.deepEqual(codes(none), ["KDM3054"]);
});

// F6 step 4: the generated declarations, checked by tsc --strict.
import { mkdirSync, mkdtempSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { spawnSync } from "node:child_process";

const REACT_STUB = `export interface HTMLAttributes<T> { className?: string; id?: string; title?: string; slot?: string; children?: unknown; onClick?: (event: unknown) => void }
export type DetailedHTMLProps<E, T> = E & { ref?: unknown; key?: string | number };
export namespace JSX { interface Element {} interface ElementChildrenAttribute { children: {} } interface IntrinsicElements { p: HTMLAttributes<HTMLElement> } }
`;
const JSX_RUNTIME_STUB = `import type { JSX as ReactJSX } from "./index";
export namespace JSX { interface Element extends ReactJSX.Element {} interface ElementChildrenAttribute extends ReactJSX.ElementChildrenAttribute {} interface IntrinsicElements extends ReactJSX.IntrinsicElements {} }
export function jsx(type: unknown, props: unknown): JSX.Element;
export function jsxs(type: unknown, props: unknown): JSX.Element;
`;

function typeCheck(files) {
  const dir = mkdtempSync(join(tmpdir(), "kadam-dts-"));
  mkdirSync(join(dir, "node_modules", "react"), { recursive: true });
  writeFileSync(join(dir, "node_modules", "react", "package.json"), '{"name":"react","types":"index.d.ts"}');
  writeFileSync(join(dir, "node_modules", "react", "index.d.ts"), REACT_STUB);
  writeFileSync(join(dir, "node_modules", "react", "jsx-runtime.d.ts"), JSX_RUNTIME_STUB);
  for (const file of compileWebComponents({ projectRoot: ROOT }).files) writeFileSync(join(dir, file.path), file.contents);
  for (const [path, text] of Object.entries(files)) writeFileSync(join(dir, path), text);
  writeFileSync(join(dir, "tsconfig.json"), JSON.stringify({
    compilerOptions: { strict: true, noEmit: true, target: "es2022", module: "esnext", moduleResolution: "bundler", jsx: "react-jsx", lib: ["es2022", "dom"], types: [] },
    include: Object.keys(files),
  }));
  const run = spawnSync(process.execPath, [join(process.cwd(), "node_modules", "typescript", "bin", "tsc"), "-p", dir], { encoding: "utf8" });
  return run.stdout + run.stderr;
}

test("kadam-elements.d.ts types tags, attributes and events under tsc --strict", () => {
  const output = typeCheck({
    "app.ts": [
      'import "./kadam-elements.js";',
      'import type { KadamPanelAttributes, KadamPanelElement } from "./kadam-elements.js";',
      'const panel = document.querySelector("kadam-panel");',
      'panel?.addEventListener("pick", (event) => { const detail: null = event.detail; void detail; });',
      'const made: KadamPanelElement = document.createElement("kadam-panel");',
      "void made;",
      'const good: KadamPanelAttributes = { title: "x", variant: "compact" };',
      "void good;",
      '// @ts-expect-error the event detail is null, not text',
      'panel?.addEventListener("pick", (event) => { const detail: string = event.detail; void detail; });',
      "// @ts-expect-error title is required",
      'const missing: KadamPanelAttributes = { link: "https://example.com" };',
      "void missing;",
      "// @ts-expect-error there is no wide variant",
      'const wide: KadamPanelAttributes = { title: "x", variant: "wide" };',
      "void wide;",
      "",
    ].join("\n"),
  });
  assert.equal(output, "");
});

test("kadam-elements.react.d.ts types JSX for the elements", () => {
  const output = typeCheck({
    "app.tsx": [
      'import "./kadam-elements.js";',
      'import type {} from "./kadam-elements.react.js";',
      'export const ok = <kadam-panel title="Hi" variant="compact" onpick={(event) => { const detail: null = event.detail; void detail; }}><p slot="footer">x</p></kadam-panel>;',
      "// @ts-expect-error title is required",
      "export const missing = <kadam-panel />;",
      "// @ts-expect-error there is no wide variant",
      'export const wide = <kadam-panel title="x" variant="wide" />;',
      "// @ts-expect-error a misspelled attribute",
      'export const typo = <kadam-panel title="x" titel="y" />;',
      "",
    ].join("\n"),
  });
  assert.equal(output, "");
});
