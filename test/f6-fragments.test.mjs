import { test } from "node:test";
import assert from "node:assert/strict";

import { compileText } from "../dist/compiler/compile.js";
import { compileProject } from "../dist/compiler/project.js";
import { scopeCss } from "../dist/compiler/fragment.js";

// F6 (D-43): fragments for existing pages.

const file = (result, path) => String(result.files.find((f) => f.path === path)?.contents ?? "");
const SOURCE = [
  "kadam 0.3", 'page "Pricing" {', "    the page background is #FAF8F3", "    the brand color is #0F766E",
  "    plan {", "        a card", "        title {", "            a section heading", '            the text says "Pro"', "        }",
  "        buy {", "            a button", '            the text says "Buy"', "            has a brand background",
  "            it remembers bought, a boolean that starts as false", "            when clicked, set bought to true", "        }",
  "    }", "}", "",
].join("\n");

test("scopeCss puts page-wide rules on the wrapper and leaves Kadam classes alone", () => {
  const css = [
    "/* x */", "", "*,\n*::before {\n  box-sizing: border-box;\n}", "html,\nbody {\n  margin: 0;\n}", "body {\n  color: red;\n}",
    ":root {\n  --kdm-color-brand: #0F766E;\n}", ".kdm-page {\n  display: block;\n}", "dialog.kdm-kind-dialog {\n  padding: 0;\n}",
    "[data-kdm-hidden] {\n  display: none !important;\n}", "[data-kdm-id=\"x\"] {\n  top: 0;\n}",
    "@media (prefers-color-scheme: dark) {\n  :root {\n    --kdm-color-brand: #5EEAD4;\n  }\n  body {\n    color: white;\n  }\n}",
    "@keyframes kdm-fade-in {\n  from {\n    opacity: 0;\n  }\n}", "@font-face {\n  font-family: \"X\";\n}", "",
  ].join("\n\n");
  assert.equal(scopeCss(css), [
    "/* x */", "", ".kdm-fragment *,\n.kdm-fragment *::before {\n  box-sizing: border-box;\n}", ".kdm-fragment {\n  margin: 0;\n}",
    ".kdm-fragment {\n  color: red;\n}", ".kdm-fragment {\n  --kdm-color-brand: #0F766E;\n}", ".kdm-page {\n  display: block;\n}",
    "dialog.kdm-kind-dialog {\n  padding: 0;\n}", ".kdm-fragment [data-kdm-hidden] {\n  display: none !important;\n}", "[data-kdm-id=\"x\"] {\n  top: 0;\n}",
    "@media (prefers-color-scheme: dark) {\n  .kdm-fragment {\n    --kdm-color-brand: #5EEAD4;\n  }\n  .kdm-fragment {\n    color: white;\n  }\n}",
    "@keyframes kdm-fade-in {\n  from {\n    opacity: 0;\n  }\n}", "@font-face {\n  font-family: \"X\";\n}", "",
  ].join("\n\n"));
});

test("a fragment build writes markup, one scoped stylesheet, and the runtime", () => {
  const result = compileText("pricing.kdm", SOURCE, { fragment: true });
  assert.deepEqual(result.diagnostics, []);
  assert.deepEqual(result.files.map((f) => f.path), [
    "assets/kadam.home.fragment.css", "assets/kadam.home.fragment.noscript.css", "assets/kadam.home.js", "fragments/home.html",
  ]);
  const html = file(result, "fragments/home.html");
  assert.doesNotMatch(html.split("-->")[1], /<html|<head|<body|<main|<title/);
  assert.match(html, /^<!-- Generated by Kadam from pricing\.kdm\. Do not edit\./);
  assert.match(html, /<link rel="stylesheet" href="\/assets\/kadam\.home\.fragment\.css">/);
  assert.match(html, /<script type="module" src="\/assets\/kadam\.home\.js"><\/script>/);
  assert.match(html, /<div class="kdm-fragment kdm-page" data-kdm-fragment="home">\n  <div class="kdm-home-plan kdm-kind-card"/);
  const css = file(result, "assets/kadam.home.fragment.css");
  // No rule outside the wrapper can match the host page.
  for (const selector of css.replace(/\/\*[^*]*\*\//g, "").match(/^[^\s@}][^{]*(?=\{)/gm)) {
    for (const part of selector.split(",").map((s) => s.trim())) {
      assert.ok(/^(\.kdm-|[a-z]+\.kdm-|\[data-kdm-id)/.test(part) || /^(from|to|\d+%)$/.test(part), part);
    }
  }
  assert.match(css, /\.kdm-fragment \{\n {2}background-color: #faf8f3;|\.kdm-fragment \{\n {2}background-color: var\(--kdm-color/i);
  assert.match(css, /\.kdm-fragment \{[^}]*--kdm-color-brand: #0f766e;/i);
});

test("a fragment without state needs no script, and a normal build is unchanged", () => {
  const plain = compileText("a.kdm", ["kadam 0.3", 'page "A" {', "    t1 {", "        a paragraph", '        the text says "Hi"', "    }", "}", ""].join("\n"), { fragment: true });
  assert.deepEqual(plain.files.map((f) => f.path), ["assets/kadam.home.fragment.css", "fragments/home.html"]);
  assert.doesNotMatch(file(plain, "fragments/home.html"), /<script/);
  const site = compileText("pricing.kdm", SOURCE);
  assert.deepEqual(site.files.map((f) => f.path).sort(), ["assets/kadam.css", "assets/kadam.home.css", "assets/kadam.home.js", "assets/kadam.home.noscript.css", "index.html"]);
});

test("a project builds one fragment per page with its assets and a base path", () => {
  const result = compileProject({ projectRoot: "examples/reference/blog", fragment: true, basePath: "/kadam" });
  assert.deepEqual(result.diagnostics.filter((d) => d.severity === "error"), []);
  const fragments = result.files.filter((f) => f.path.startsWith("fragments/")).map((f) => f.path);
  assert.ok(fragments.length >= 2, fragments.join());
  assert.ok(!result.files.some((f) => f.path.endsWith("index.html") || f.path === "assets/kadam.css"));
  assert.match(String(result.files.find((f) => f.path.startsWith("fragments/")).contents), /href="\/kadam\/assets\/kadam\.[a-z0-9-]+\.fragment\.css"/);
});
